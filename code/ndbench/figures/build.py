"""`figures.build`: write every summary benchmark as a paper figure (`python -m code.ndbench
figures --out <store> --fig-dir <dir>`).

For each numbered item of the summary page (`dash.summary.numbering`): `figNN_<key>.{pdf,svg,png}`
(vector PDF with TrueType fonts for LaTeX, SVG, 300-dpi PNG), `tabNN_<key>.tex` for a benchmark
the page shows as a booktabs table (plus its forest-plot variant `fig_<key>.*`), and
`captions.md` with the NeurIPS-style caption of each. Numbers come from `dash.summary.chart_data`,
the same objects the page tabulates.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from ..dash import summary
from ..dash.chart_data import ChartData
from ..store import Store
from . import plots, tables
from . import style as S


def _slug(label: str) -> str:
    kind, _sp, n = label.partition(" ")
    return f"{'fig' if kind == 'Figure' else 'tab'}{int(n):02d}"


def write_figures(charts: Sequence[ChartData], fig_dir: Path) -> list[Path]:
    """Write all figure/table files and `captions.md` for already-computed `charts`."""
    fig_dir = Path(fig_dir)
    fig_dir.mkdir(parents=True, exist_ok=True)
    nums = summary.numbering(charts)
    written: list[Path] = []
    md = [
        "# Figure and table captions",
        "",
        "NeurIPS-style captions for the files in this directory, in page order. Generated by "
        "`python -m code.ndbench figures`; numbers come from the same data as the summary page.",
        "",
    ]
    with S.paper_style():
        if any(c.kind != "missing" for c in charts):
            fig = plots.fig_overview(charts)
            base = fig_dir / "fig01_overview"
            written += S.save(fig, base)
            S.close(fig)
            md += [
                "## Figure 1 (`fig01_overview.pdf`)",
                "",
                f"**Figure 1:** {summary.OVERVIEW_TITLE}. {summary.overview_caption(charts, nums)}",
                "",
            ]
        order = sorted(charts, key=lambda c: _order_key(nums.get(c.key, "")))
        for cd in order:
            label = nums.get(cd.key)
            if label is None:
                continue
            slug = _slug(label)
            caption = summary.caption_text(cd, None)
            if cd.kind == "missing":
                md += [f"## {label} ({cd.key})", "", f"**{label}:** {caption}", ""]
                continue
            files: list[str] = []
            if cd.as_table:
                tex = fig_dir / f"{slug}_{cd.key}.tex"
                tex.write_text(tables.to_latex(cd, label, caption))
                written.append(tex)
                files.append(tex.name)
                base = fig_dir / f"fig_{cd.key}"
            else:
                base = fig_dir / f"{slug}_{cd.key}"
            fig = plots.render(cd)
            if fig is not None:
                written += S.save(fig, base)
                S.close(fig)
                files.append(base.with_suffix(".pdf").name)
            note = (
                " (forest-plot variant of the table: `" + base.name + ".pdf`)"
                if cd.as_table
                else ""
            )
            md += [
                f"## {label} (`{files[0]}`){note}",
                "",
                f"**{label}:** {caption}",
                "",
            ]
    cap = fig_dir / "captions.md"
    cap.write_text("\n".join(md))
    written.append(cap)
    return written


def _order_key(label: str) -> tuple[int, int]:
    kind, _sp, n = label.partition(" ")
    return (0 if kind == "Figure" else 1, int(n) if n.isdigit() else 0)


def build_figures(store: Store, fig_dir: Path) -> list[Path]:
    """Compute the summary benchmarks from `store` and write their figures into `fig_dir`."""
    return write_figures(summary.chart_data(store), Path(fig_dir))
