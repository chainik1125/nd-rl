def _tex(text: str) -> str:
    """Plain-text LaTeX escape for the Dan-only tables (cells are page HTML: tags dropped)."""
    import html
    import re

    text = re.sub(r"<[^>]+>", " ", text).replace("&minus;", "-")
    text = html.unescape(re.sub(r"\s+", " ", text).strip())
    out = text.replace("\\", r"\textbackslash{}")
    for ch in "&%$#_{}":
        out = out.replace(ch, "\\" + ch)
    for sym, tex in (
        ("δ", r"$\delta$"),
        ("α", r"$\alpha$"),
        ("−", "-"),
        ("≥", r"$\geq$"),
        ("≤", r"$\leq$"),
        ("↳", r"$\hookrightarrow$"),
        ("∧", r"$\wedge$"),
        ("→", r"$\to$"),
    ):
        out = out.replace(sym, tex)
    return out


def dan_only_table_tex(cd: ChartData, label: str, caption: str) -> str:
    """A booktabs `table` float of a Dan-only page table (caption above, no vertical rules)."""
    table = cd.extra["table"]
    headers = list(table["headers"])
    align = str(table.get("align") or "l" * len(headers))
    lines = [
        r"\begin{table}[t]",
        r"  \caption{" + _tex(caption) + "}",
        r"  \label{tab:" + cd.key + "}",
        r"  \centering",
        r"  \begin{tabular}{" + align + "}",
        r"    \toprule",
        "    " + " & ".join(_tex(h) for h in headers) + r" \\",
        r"    \midrule",
    ]
    for row in table["rows"]:
        lines.append("    " + " & ".join(_tex(str(c)) for c in row) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    del label
    return "\n".join(lines)


def build_dan_only_figures(store: Store, fig_dir: Path) -> list[Path]:
    """`figures --dan-only`: the Dan-only page's figures (`fig01_overview`, `figNN_do_<key>`,
    PDF/SVG/PNG), its tables (`tabNN_do_<key>.tex`) and `captions.md`, from the same
    `dash.dan_only.dan_only_chart_data` the page draws."""
    from ..dash import dan_only
    from . import dan_only as F

    fig_dir = Path(fig_dir)
    fig_dir.mkdir(parents=True, exist_ok=True)
    charts = dan_only.dan_only_chart_data(store)
    nums = dan_only.numbering(charts)
    written: list[Path] = []
    md = [
        "# Figure and table captions (Dan-only page)",
        "",
        "Generated by `python -m code.ndbench figures --dan-only`; numbers come from the same "
        "data as the page (`dash --summary --dan-only`).",
        "",
    ]
    with S.paper_style():
        if any(c.kind != "missing" for c in charts):
            fig = F.fig_overview(charts)
            written += S.save(fig, fig_dir / "fig01_overview")
            S.close(fig)
            md += [
                "## Figure 1 (`fig01_overview.pdf`)",
                "",
                f"**Figure 1:** {dan_only.OVERVIEW_TITLE}. "
                f"{dan_only.overview_caption(charts, nums)}",
                "",
            ]
        for cd in charts:
            label = nums.get(cd.key)
            if label is None:
                continue
            caption = dan_only.caption_text(cd, None)
            if cd.kind == "missing":
                md += [f"## {label} ({cd.key})", "", f"**{label}:** {caption}", ""]
                continue
            if cd.kind == "table":
                tex = fig_dir / f"{_slug(label)}_{cd.key}.tex"
                tex.write_text(dan_only_table_tex(cd, label, caption))
                written.append(tex)
                md += [f"## {label} (`{tex.name}`)", "", f"**{label}:** {caption}", ""]
                continue
            fig = F.render(cd)
            if fig is None:
                continue
            base = fig_dir / f"{_slug(label)}_{cd.key}"
            written += S.save(fig, base)
            S.close(fig)
            md += [f"## {label} (`{base.name}.pdf`)", "", f"**{label}:** {caption}", ""]
    cap = fig_dir / "captions.md"
    cap.write_text("\n".join(md))
    written.append(cap)
    return written
