from nd_environment import strict_complete
import numpy as np
import torch
from torch import nn
from torch.distributions import Categorical

P = ("atom", "P")
DISTRACTORS = [("atom", x) for x in "QRS"]
FEATURE_NAMES = [
    "rule_left", "rule_right", "result_atom", "result_and",
    "source_left_atom", "source_left_and", "source_right_atom", "source_right_and",
    "result_equals_goal", "source_left_equals_goal", "source_right_equals_goal",
    "source_is_newest", "source_relative_age", "source_log_size", "result_log_size",
    "result_left_atom", "result_left_and", "result_right_atom", "result_right_and",
    "source_scope_depth", "source_visible", "destination_scope_depth",
]
STATE_NAMES = ["available_conjunction_fraction", "last_is_conjunction", "log_available_actions",
               "last_log_size", "active_scope_depth", "goal_is_atom"]


def fsize(f):
    return 1 if f[0] == "atom" else 1 + fsize(f[1]) + fsize(f[2])


def size_feature(f):
    z = math.log(fsize(f))
    return z / (1 + z)


def kind(f):
    return [float(f[0] == "atom"), float(f[0] == "and")]


def line_text(index, formula, rule, refs=()):
    return " ".join([f"N{index}", formula_text(formula), ":", rule] + [f"N{r}" for r in refs] + [";"])


def distractor_tree(rng, depth):
    if depth == 0:
        return rng.choice(DISTRACTORS)
    return ("and", distractor_tree(rng, depth - 1), distractor_tree(rng, depth - 1))


def make_task(rng, depth, family="spine"):
    """Unique P at depth d; each projection on its root-to-leaf path is necessary.

    The bound is for the restricted projection calculus. A conjunction-only
    assumption and atomic goal also have this normal ND proof; no claim that
    arbitrary ND certificates cannot use alternative derived lemmas is needed.
    """
    f, reversed_directions = P, []
    for _ in range(depth):
        side = rng.randrange(2)
        decoy = rng.choice(DISTRACTORS) if family == "spine" else distractor_tree(rng, rng.randint(1, 3))
        f = ("and", f, decoy) if side == 0 else ("and", decoy, f)
        reversed_directions.append(side)
    directions = reversed_directions[::-1]
    prompt = f"THM {formula_text(f)} SEQ P PRF"
    current, body = f, [line_text(1, f, "PR")]
    for i, side in enumerate(directions, 2):
        current = current[side + 1]
        body.append(line_text(i, current, "ANDE1" if side == 0 else "ANDE2", (i - 1,)))
    record = {"prompt": prompt, "body": " ".join(body) + " QED", "depth": depth,
              "family": family, "directions": directions, "n_lines": depth + 1,
              "source_id": theorem_hash(prompt)}
    if not strict_complete(prompt, record["body"])["ok"]:
        raise AssertionError("Generated source failed independent verifiers")
    return record


@dataclass(frozen=True)
class Action:
    source: int
    side: int
    result: tuple


class Environment:
    """Only zero-scope ANDE1/ANDE2, duplicate results suppressed globally.

    Premise registration is deterministic environment initialization. The
    policy gets no proof prefix when cut=0; PR counts in certificate length.
    """
    def __init__(self, row, cut=0, budget=None):
        from nd_environment import parse_prompt
        premises, self.goal = parse_prompt(row["prompt"])
        if len(premises) != 1:
            raise ValueError("Exactly one premise required")
        self.row = row
        self.formulas = [premises[0]]
        self.certificate = [line_text(1, premises[0], "PR")]
        self.refs = [()]
        self.cut, self.steps = cut, 0
        self.budget = row["depth"] - cut if budget is None else budget
        for side in row["directions"][:cut]:
            self._add(Action(len(self.formulas) - 1, side, self.formulas[-1][side + 1]))
        self.steps = 0

    def _add(self, a):
        if self.formulas[a.source][0] != "and" or self.formulas[a.source][a.side + 1] != a.result:
            raise AssertionError("Illegal projection")
        self.formulas.append(a.result)
        self.refs.append((a.source,))
        self.certificate.append(line_text(len(self.formulas), a.result,
                                          "ANDE1" if a.side == 0 else "ANDE2", (a.source + 1,)))

    def actions(self):
        existing, offered, actions = set(self.formulas), set(), []
        for i, f in enumerate(self.formulas):
            if f[0] != "and":
                continue
            for side in (0, 1):
                result = f[side + 1]
                if result not in existing and result not in offered:
                    actions.append(Action(i, side, result))
                    offered.add(result)
        return actions

    def features(self, actions):
        rows = []
        n = len(self.formulas)
        for a in actions:
            f, g = self.formulas[a.source], a.result
            children = kind(g[1]) + kind(g[2]) if g[0] == "and" else [0.] * 4
            rows.append([float(a.side == 0), float(a.side == 1)] + kind(g) + kind(f[1]) + kind(f[2]) +
                        [float(g == self.goal), float(f[1] == self.goal), float(f[2] == self.goal),
                         float(a.source == n - 1), (n - 1 - a.source) / n,
                         size_feature(f), size_feature(g)] + children + [0., 1., 0.])
        state = [sum(f[0] == "and" for f in self.formulas) / n,
                 float(self.formulas[-1][0] == "and"), math.log1p(len(actions)) / 5,
                 size_feature(self.formulas[-1]), 0., 1.]
        return np.asarray(rows, np.float32), np.asarray(state, np.float32)

    def step(self, action):
        self._add(action)
        self.steps += 1
        success = action.result == self.goal
        done = success or self.steps >= self.budget or not self.actions()
        if success:
            verdict = strict_complete(self.row["prompt"], self.body())
            if not verdict["ok"]:
                raise AssertionError(verdict)
        return float(success), done

    def body(self):
        return " ".join(self.certificate) + " QED"

    def pruned_body(self):
        keep = set()
        def visit(i):
            if i not in keep:
                keep.add(i)
                for parent in self.refs[i]:
                    visit(parent)
        visit(len(self.formulas) - 1)
        ordered = sorted(keep)
        renumber = {old: new + 1 for new, old in enumerate(ordered)}
        out = []
        for i in ordered:
            if i == 0:
                out.append(line_text(renumber[i], self.formulas[i], "PR"))
            else:
                parent = self.refs[i][0]
                side = 0 if self.formulas[parent][1] == self.formulas[i] else 1
                out.append(line_text(renumber[i], self.formulas[i], "ANDE1" if side == 0 else "ANDE2",
                                     (renumber[parent],)))
        return " ".join(out) + " QED"


class Policy(nn.Module):
    def __init__(self, width=64):
        super().__init__()
        def mlp(n):
            return nn.Sequential(nn.Linear(n, width), nn.Tanh(), nn.Linear(width, width), nn.Tanh(),
                                 nn.Linear(width, width), nn.Tanh(), nn.Linear(width, 1))
        self.scorer, self.critic = mlp(len(FEATURE_NAMES) + len(STATE_NAMES)), mlp(len(STATE_NAMES))

    def forward(self, actions, state, mask=None):
        expanded = state.unsqueeze(-2).expand(*actions.shape[:-1], state.shape[-1])
        logits = self.scorer(torch.cat((actions, expanded), -1)).squeeze(-1)
        if mask is not None:
            logits = logits.masked_fill(~mask, -torch.inf)
        return logits, self.critic(state).squeeze(-1)


def exact_random_probability(row):
    env, prob = Environment(row), 1.
    for side in row["directions"]:
        actions = env.actions()
        prob /= len(actions)
        desired = env.formulas[-1][side + 1]
        a = next(a for a in actions if a.result == desired)
        env.step(a)
    return prob


def generate(args):
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(190513100)
    seeds = [make_task(rng, 5) for _ in range(2)]
    seen = {x["source_id"] for x in seeds}
    def population(depths, n, families):
        rows = []
        for family in families:
            for depth in depths:
                accepted = 0
                while accepted < n:
                    row = make_task(rng, depth, family)
                    if row["source_id"] in seen:
                        continue
                    seen.add(row["source_id"])
                    row["analytic_random_minbudget_success"] = exact_random_probability(row)
                    rows.append(row)
                    accepted += 1
        return rows
    dev = population([6, 9], 8, ["spine", "compound_decoy"])
    final = population([5, 15, 31, 63], 16, ["spine", "compound_decoy"])
    for name, rows in [("seeds", seeds), ("dev", dev), ("final", final)]:
        common.write_jsonl(out / f"symbolic_{name}.jsonl", rows)
    common.write_json(out / "symbolic_manifest.json", {
        "generator_seed": 190513100, "external_seed_count": 2, "external_seed_max_lines": 6,
        "counts": {"seeds": len(seeds), "dev": len(dev), "final": len(final)},
        "hashes": {p.name: common.sha(p) for p in out.glob("symbolic_*.jsonl")},
        "canonical_exclusions": "All sets mutually disjoint under PQRS renaming and premise permutation",
        "final_reference_labels": "Audit only; training loads symbolic_seeds.jsonl exclusively",
        "feature_names": FEATURE_NAMES, "state_names": STATE_NAMES,
    })


def batch_transitions(transitions):
    count = len(transitions)
    width = max(len(t["actions"]) for t in transitions)
    a = torch.zeros(count, width, len(FEATURE_NAMES))
    m = torch.zeros(count, width, dtype=torch.bool)
    for i, t in enumerate(transitions):
        a[i, :len(t["actions"])] = torch.from_numpy(t["actions"])
        m[i, :len(t["actions"])] = True
    return a, torch.from_numpy(np.stack([t["state"] for t in transitions])), m


def train(args):
    torch.set_num_threads(args.threads)
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    rng = random.Random(args.seed)
    sources = common.read_jsonl(args.sources)
    if any(s["n_lines"] > 6 or not strict_complete(s["prompt"], s["body"])["ok"] for s in sources):
        raise ValueError("Every external source must be independently verified and cap six")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if (out / "symbolic_checkpoint.pt").exists():
        raise ValueError("Refusing to overwrite existing run")
    model = Policy()
    config = {k: v for k, v in vars(args).items() if k != "fn"}
    config.update({"source_sha256": common.sha(args.sources), "code_sha256": common.sha(__file__),
                   "vendor_hashes": common.dependency_hashes(), "pid": os.getpid(),
                   "start_unix": time.time(), "terminal_reward_only": True, "gamma": 1.,
                   "gae_lambda": .95, "width": 64, "model_parameters": sum(p.numel() for p in model.parameters()),
                   "environment_sha256": common.sha(Path(__file__).with_name("nd_environment.py")),
                   "protocol_sha256": common.sha(common.ROOT / "reports/symbolic_protocol.md")})
    common.write_json(out / "symbolic_config.json", config)
    optimizer = torch.optim.Adam(model.parameters(), lr=3e-4)
    cuts = [s["depth"] - 1 if args.mode == "reset" else 0 for s in sources]
    histories = [deque(maxlen=64) for s in sources]
    total, update, started = 0, 0, time.monotonic()
    metrics = []
    accounting = Counter()
    torch.save({"state_dict": model.state_dict(), "config": config}, out / "symbolic_initial.pt")
    while total < args.steps:
        transitions, episode_rows = [], []
        while len(transitions) < min(args.batch, args.steps - total):
            source_index = rng.randrange(len(sources))
            source, cut = sources[source_index], cuts[source_index]
            env = Environment(source, cut=cut)
            accounting["episodes_started"] += 1
            accounting["registered_premise_lines"] += 1
            accounting["replayed_prefix_projections"] += cut
            episode, reward, done = [], 0., False
            while not done and len(transitions) + len(episode) < args.steps - total:
                actions = env.actions()
                af, sf = env.features(actions)
                with torch.no_grad():
                    logits, value = model(torch.from_numpy(af), torch.from_numpy(sf))
                    dist = Categorical(logits=logits)
                    action = dist.sample()
                    old_logp = dist.log_prob(action).item()
                reward, done = env.step(actions[action.item()])
                episode.append({"actions": af, "state": sf, "action": action.item(), "logp": old_logp,
                                "value": value.item(), "reward": reward, "done": done})
            # Artificial final-budget truncation is bootstrapped; no false terminal zero.
            next_value = 0.
            if not done:
                af, sf = env.features(env.actions())
                with torch.no_grad():
                    next_value = model(torch.from_numpy(af), torch.from_numpy(sf))[1].item()
            advantage = 0.
            for t in reversed(episode):
                delta = t["reward"] + next_value * (not t["done"]) - t["value"]
                advantage = delta + .95 * (not t["done"]) * advantage
                t["advantage"], t["return"] = advantage, advantage + t["value"]
                next_value = t["value"]
            transitions.extend(episode)
            if done:
                accounting["episodes_completed"] += 1
                accounting["episodes_successful"] += int(reward)
                histories[source_index].append(reward)
                episode_rows.append({"source_index": source_index, "cut": cut, "success": reward,
                                     "steps": len(episode)})
                if (args.mode == "reset" and cut > 0 and len(histories[source_index]) == 64 and
                        np.mean(histories[source_index]) >= .9):
                    cuts[source_index] -= 1
                    histories[source_index].clear()
        aa, ss, mm = batch_transitions(transitions)
        chosen = torch.tensor([t["action"] for t in transitions])
        old_logps = torch.tensor([t["logp"] for t in transitions])
        advantages = torch.tensor([t["advantage"] for t in transitions])
        advantages = (advantages - advantages.mean()) / (advantages.std(unbiased=False) + 1e-8)
        returns = torch.tensor([t["return"] for t in transitions])
        losses = []
        for _ in range(4):
            logits, values = model(aa, ss, mm)
            dist = Categorical(logits=logits)
            logps = dist.log_prob(chosen)
            ratio = (logps - old_logps).exp()
            policy_loss = -torch.minimum(ratio * advantages, ratio.clamp(.8, 1.2) * advantages).mean()
            value_loss = .5 * (values - returns).square().mean()
            entropy = dist.entropy().mean()
            loss = policy_loss + value_loss - .01 * entropy
            optimizer.zero_grad()
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), .5)
            optimizer.step()
            losses.append(float(loss.detach()))
        total += len(transitions)
        update += 1
        metric = {"update": update, "actions": total, "cuts": cuts.copy(),
                  "episodes": len(episode_rows), "success": float(np.mean([e["success"] for e in episode_rows])),
                  "mean_cut": float(np.mean([e["cut"] for e in episode_rows])), "loss": float(np.mean(losses)),
                  "entropy": float(entropy.detach()), "seconds": time.monotonic() - started,
                  "accounting": dict(accounting)}
        metrics.append(metric)
        if update % 4 == 0 or total == args.steps:
            common.write_jsonl(out / "symbolic_metrics.jsonl", metrics)
            print(json.dumps(metric), flush=True)
    payload = {"state_dict": model.state_dict(), "optimizer": optimizer.state_dict(), "config": config,
               "actions": total, "updates": update, "optimizer_steps": 4 * update, "cuts": cuts,
               "elapsed_seconds": time.monotonic() - started, "accounting": dict(accounting)}
    torch.save(payload, out / "symbolic_checkpoint.pt")
    common.write_json(out / "symbolic_train_summary.json", {k: v for k, v in payload.items() if k not in ("state_dict", "optimizer")})


def evaluate(args):
    torch.set_num_threads(args.threads)
    torch.manual_seed(args.seed)
    rows = common.read_jsonl(args.population)
    rng = random.Random(args.seed)
    model = Policy()
    if args.policy == "model":
        ckpt = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
        model.load_state_dict(ckpt["state_dict"])
    model.eval()
    attempts = []
    for row in rows:
        for attempt in range(args.attempts):
            budget = row["depth"] + (3 if args.budget == "loose" else 0)
            env, done, reward = Environment(row, budget=budget), False, 0.
            actions_taken = []
            while not done:
                actions = env.actions()
                if args.policy == "random":
                    idx = rng.randrange(len(actions))
                elif args.policy == "heuristic":
                    # Fully specified nonlearned projection-spine heuristic.
                    idx = max(range(len(actions)), key=lambda i: (actions[i].result == env.goal,
                              actions[i].result[0] == "and", actions[i].source))
                else:
                    af, sf = env.features(actions)
                    with torch.no_grad():
                        logits, _ = model(torch.from_numpy(af), torch.from_numpy(sf))
                        idx = (Categorical(logits=logits).sample() if args.sample else logits.argmax()).item()
                a = actions[idx]
                actions_taken.append([a.source + 1, a.side])
                reward, done = env.step(a)
            body = env.body()
            verdict = strict_complete(row["prompt"], body)
            pruned = env.pruned_body() if reward else None
            pruned_verdict = strict_complete(row["prompt"], pruned) if pruned else None
            if bool(reward) != verdict["ok"] or (reward and not pruned_verdict["ok"]):
                raise AssertionError("Environment and independent certificates disagree")
            attempts.append({"source_id": row["source_id"], "prompt": row["prompt"], "family": row["family"],
                             "depth": row["depth"], "reference_lines": row["n_lines"], "attempt": attempt,
                             "policy": args.policy, "sample": args.sample, "budget": budget,
                             "success": bool(reward), "generated_actions": env.steps, "body": body,
                             "verdict": verdict, "pruned_body": pruned, "pruned_verdict": pruned_verdict,
                             "action_trace": actions_taken,
                             "analytic_random_minbudget_success": row["analytic_random_minbudget_success"]})
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    common.write_jsonl(out / "symbolic_attempts.jsonl", attempts)
    groups = {}
    for family, depth in sorted({(x["family"], x["depth"]) for x in attempts}):
        group = [x for x in attempts if x["family"] == family and x["depth"] == depth]
        groups[f"{family}/d{depth}"] = {"n": len(group), "successes": sum(x["success"] for x in group),
          "success_rate": float(np.mean([x["success"] for x in group])),
          "mean_generated_actions": float(np.mean([x["generated_actions"] for x in group])),
          "mean_random_analytic": float(np.mean([x["analytic_random_minbudget_success"] for x in group])),
          "pruned_success_lines": sorted(set(x["pruned_verdict"]["n_lines"] for x in group if x["success"]))}
    common.write_json(out / "symbolic_eval_summary.json", {"groups": groups,
        "config": {k: v for k, v in vars(args).items() if k != "fn"},
        "population_sha256": common.sha(args.population), "code_sha256": common.sha(__file__),
        "checkpoint_sha256": common.sha(args.checkpoint) if args.checkpoint else None})
    print(json.dumps(groups, sort_keys=True), flush=True)


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("generate")
    p.add_argument("--out", required=True)
    p.set_defaults(fn=generate)
    p = sub.add_parser("train")
    p.add_argument("--sources", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--mode", choices=["full", "reset"], required=True)
    p.add_argument("--seed", type=int, required=True)
    p.add_argument("--steps", type=int, default=8192)
    p.add_argument("--batch", type=int, default=256)
    p.add_argument("--threads", type=int, default=4)
    p.set_defaults(fn=train)
    p = sub.add_parser("evaluate")
    p.add_argument("--population", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--policy", choices=["model", "untrained", "random", "heuristic"], required=True)
    p.add_argument("--checkpoint")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--attempts", type=int, default=1)
    p.add_argument("--budget", choices=["minimal", "loose"], default="minimal")
    p.add_argument("--sample", action="store_true")
    p.add_argument("--threads", type=int, default=4)
    p.set_defaults(fn=evaluate)
    args = parser.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
