"""base_saturation table (PREREG): every arm on Charles149 at k1024, seed 0, against the base,
CPT_s0 and the paper's RL (L3 end s0).

    ND_OFFLINE=1 PYTHONDONTWRITEBYTECODE=1 python -m \
        code.experiments.current.base_saturation_20261105.table

Existing reads: /scratch/cowifornia/nd-rl/think/runs/eval/v2/charles149_{s1g3,cpt_s1g3,
grpo_think_vs_mb_kkl0}_s0_plain_k1024. New reads (merge.py):
/scratch/cowifornia/nd-rl/base_saturation/final/charles149_sat_<arm>_s0_plain_k1024. Arms not
read yet are skipped. Val loss from the pulled A and C train.json. Writes table.json and table.md
next to this file.
"""

from __future__ import annotations

import json
from pathlib import Path

from code.thinking import stats

V2 = Path("/scratch/cowifornia/nd-rl/think/runs/eval/v2")
S = Path("/scratch/cowifornia/nd-rl/base_saturation")
KEEP_FILE = Path("/scratch/cowifornia/nd-rl/think/runs/pools/charles_1002/charles_clean.jsonl")
HERE = Path(__file__).resolve().parent
KS = [1, 5, 64, 1024]
N = 1024
READS = {
    "base": V2 / "charles149_s1g3_s0_plain_k1024",
    "B0.25": S / "final/charles149_sat_B78_s0_plain_k1024",
    "CPT": V2 / "charles149_cpt_s1g3_s0_plain_k1024",
    "B4": S / "final/charles149_sat_B1248_s0_plain_k1024",
    "A": S / "final/charles149_sat_A_s0_plain_k1024",
    "C": S / "final/charles149_sat_C_s0_plain_k1024",
    "RL": V2 / "charles149_grpo_think_vs_mb_kkl0_s0_plain_k1024",
    "D1": S / "final/charles149_sat_D1_s0_plain_k1024",
    "D2": S / "final/charles149_sat_D2_s0_plain_k1024",
}
#: PREREG's paired gaps (x - y), and its one-arm-only pairs at k1024
GAPS = [("CPT", "base"), ("RL", "base"), ("A", "base"), ("A", "CPT"), ("B0.25", "base"),
        ("CPT", "B0.25"), ("B4", "CPT"), ("C", "base"), ("C", "CPT"), ("D1", "CPT"),
        ("RL", "D1"), ("D2", "C"), ("D2", "RL")]  # fmt: skip
ONLY = [("RL", "D1"), ("D1", "CPT"), ("D2", "C"), ("C", "base"), ("A", "base"), ("A", "CPT")]
#: added after the PREREG (descriptive; marked † in table.md): every arm against base and CPT,
#: and RL against A (the anneal-only arm). Write-up (2026-11-05, after all reads): RL against
#: every pretraining-only arm, so "how close does each arm get to RL at large k" has intervals.
EXTRA_GAPS = [("RL", "A"), ("B4", "base"), ("C", "A"), ("D1", "base"), ("D2", "base"),
              ("D2", "CPT"), ("RL", "CPT"), ("RL", "B0.25"), ("RL", "B4"),
              ("RL", "C")]  # fmt: skip
EXTRA_ONLY = [("RL", "A"), ("B0.25", "base"), ("B0.25", "CPT"), ("B4", "CPT"), ("C", "CPT"),
              ("D2", "RL"), ("RL", "C")]  # fmt: skip
VAL = {
    "A": S / "pods/rp-sat-a/out/A_s0/train.json",
    "C": S / "pods/rp-sat-c/out/C_s0/train.json",
}
keep = {json.loads(x)["name"] for x in KEEP_FILE.read_text().splitlines() if x.strip()}


def rows(label: str) -> Path:
    return READS[label] / "rows_plain_B64.jsonl"


def arm(label: str) -> stats.Arm:
    a = stats.load_arm(label, [rows(label)])
    a = a.subset(sorted(keep & set(a.names)), label)
    assert len(a.names) == len(keep) == 149 and a.kmax >= N, (label, len(a.names), a.kmax)
    return a


def solved(label: str) -> set[str]:
    out = set()
    for line in rows(label).read_text().splitlines():
        r = json.loads(line)
        if r["name"] in keep and sum(r["ok"][:N]) > 0:
            out.add(r["name"])
    return out


def f(v: list[float]) -> str:
    return f"{v[0]:+.1f} [{v[1]:+.1f}, {v[2]:+.1f}]"


def main() -> int:
    have = [x for x in READS if rows(x).exists()]
    A = {x: arm(x) for x in have}
    out: dict[str, object] = {"arms": have, "reads": {x: str(READS[x]) for x in have}}
    lines = [
        "# Base saturation on Charles149, seed 0 (generated by `table.py`)",
        "",
        "pass@k in % of the 149 problems (unbiased estimator, k1024 reads). Arms not read yet are "
        "left out.",
        "",
        "| k | " + " | ".join(have) + " |",
        "|---|" + "---|" * len(have),
    ]
    pk: dict[str, dict[int, float]] = {x: {} for x in have}
    for k in KS:
        for x in have:
            pk[x][k] = 100 * float(A[x].values(k).mean())
        lines.append(f"| {k} | " + " | ".join(f"{pk[x][k]:.1f}" for x in have) + " |")
    out["pass_at_k"] = pk
    curve = {x: {k: 100 * float(A[x].values(k).mean()) for k in (1, 2, 4, 8, 16, 32, 64, 128,
             256, 512, 1024)} for x in have}  # fmt: skip
    out["curve"] = curve
    lines += [
        "",
        "Paired gaps x − y in points, 95% problem-bootstrap intervals (stats.paired_diff, one "
        "seed, 4,000 draws). Single-seed: in cpt_control, RL − CPT at pass@1024 ranged +1.3 to "
        "−4.0 across 3 seeds.",
        "",
        "| x − y | pass@1 | pass@5 | pass@64 | pass@1024 |",
        "|---|---|---|---|---|",
    ]
    gaps: dict[str, dict[int, list[float]]] = {}
    for x, y in GAPS + EXTRA_GAPS:
        if x not in A or y not in A:
            continue
        mark = "†" if (x, y) in EXTRA_GAPS else ""
        g = {}
        for k in KS:
            e = stats.paired_diff(A[x], A[y], k, draws=4000)
            g[k] = [100 * e.est, 100 * e.lo, 100 * e.hi]
        gaps[f"{x}-{y}"] = g
        lines.append(f"| {x} − {y}{mark} | " + " | ".join(f(g[k]) for k in KS) + " |")
    out["gaps"] = gaps
    lines += [
        "",
        "Problems solved at k1024 (any of 1,024 attempts) by x and never by y:",
        "",
        "| x | y | x not y | y not x | x solved | y solved |",
        "|---|---|---|---|---|---|",
    ]
    only = {}
    for x, y in ONLY + EXTRA_ONLY:
        if x not in A or y not in A:
            continue
        mark = "†" if (x, y) in EXTRA_ONLY else ""
        sx, sy = solved(x), solved(y)
        only[f"{x}|{y}"] = {
            "x_not_y": sorted(sx - sy),
            "y_not_x": sorted(sy - sx),
            "x_solved": len(sx),
            "y_solved": len(sy),
        }
        lines.append(
            f"| {x}{mark} | {y} | {len(sx - sy)} | {len(sy - sx)} | {len(sx)} | {len(sy)} |"
        )
    out["only"] = only
    lines += [
        "",
        "† added after the PREREG (descriptive): each arm against base and CPT, and RL against "
        "every pretraining-only arm.",
    ]
    vl = {}
    for x, p in VAL.items():
        if p.exists():
            t = json.loads(p.read_text())
            vl[x] = {
                "final_val": t.get("final_val"),
                "final_val_action": t.get("final_val_action"),
                "base_val": (t.get("anneal") or {}).get("base_val"),
                "curve": [(c["step"], c.get("val_loss")) for c in t.get("curve", [])],
            }
    if vl:
        lines += ["", "Held-out val loss (Stage 1's 7,000 pairs; S1g3_s0 ended at 0.0692):", ""]
        for x, v in vl.items():
            lines.append(
                f"- {x}: final val {v['final_val']:.4f} (action {v['final_val_action']:.4f})"
                + (f"; its start (the base) {v['base_val']:.4f}" if v["base_val"] else "")
            )
    out["val"] = vl
    (HERE / "table.json").write_text(json.dumps(out, indent=1))
    (HERE / "table.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
