"""Teacher-forced loss of every base_saturation model, scored exactly as cpt_control's `valloss.py`
(the circuit agent's CPU check, used read only: its `score`, sets and layout).

    python -m code.experiments.current.base_saturation_20261105.valloss

Sets: Stage 1's validation split (first 2,000 records of bench `heldout.jsonl`, 7,000 pairs, <e0>
block) and Charles149's reference proofs, same layout. `w1` = the Stage-1 val metric (think
tokens weighted 1), `w0` = action tokens only. Models: base / CPT / RL seed 0 (a check against
cpt_control's numbers) and every arm pulled to serrano so far; a model already in valloss.json is
not scored again. CPU fp32, 4 torch threads. Writes valloss.json and valloss.md next to this file.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import tempfile
import time
from pathlib import Path

import torch

HERE = Path(__file__).resolve().parent
P = Path("/scratch/cowifornia/nd-rl/base_saturation/pods")
VL = Path(
    "/scratch/cowifornia/nd-rl/worktrees/circuit-diffing/code/experiments/current/"
    "cpt_control_20261105/valloss.py"
)
G = "grpo_think_vs_mb_kkl0_{t}_s0_L3"


def l3(alias: str, tag: str) -> Path:
    n = G.format(t=tag)
    return P / alias / "out/grpo" / n / "ckpts" / f"{n}_it39.pt"


def models(vl) -> dict[str, Path]:  # noqa: ANN001
    ref = vl.ckpts(0)
    return {
        "base_s0": ref["base"],
        "cpt_s0": ref["cpt"],
        "rl_s0": ref["rl"],
        "A_s0": P / "rp-sat-a/out/A_s0/model.pt",
        "B78_s0": P / "rp-sat-b025/out/B78/cpt_lr0.00015.pt",
        "B1248_s0": P / "rp-sat-b4/out/B1248/cpt_lr0.00015.pt",
        "C_s0": P / "rp-sat-c/out/C_s0/model.pt",
        "D1_s0": l3("rp-sat-d1", "fromcpt"),
        "D2_s0": l3("rp-sat-c", "fromC2x"),
    }


def main(argv: list[str] | None = None) -> int:
    torch.set_num_threads(4)
    spec = importlib.util.spec_from_file_location("cpt_valloss", VL)
    assert spec and spec.loader
    vl = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(vl)
    from code.thinking import stateview
    from code.thinking import train as T
    from code.thinking.ckpt import load_ckpt
    from code.thinking.data import heldout_records

    data = T.load_data(vl.RUNS / "data/S1g3.pkl")
    tok = T.tokenizer_for(data)
    fmt = T.think_format(data)
    stateview.set_state_format(stateview.data_format(data))
    held = T.with_effort(heldout_records(vl.HELD, tok, data["no_trace_mode"]), tok, 0)
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td) / "charles_ref.jsonl"
        with open(tmp, "w") as f:
            for line in vl.CHARLES.read_text().splitlines():
                r = json.loads(line)
                f.write(json.dumps({"prompt": r["prompt"], "proof": r["reference_proof"]}) + "\n")
        ch = T.with_effort(heldout_records(tmp, tok, data["no_trace_mode"], limit=10_000), tok, 0)
    sets = {
        "val": T.make_data(held, fmt, tok, "cpu"),
        "charles_ref": T.make_data(ch, fmt, tok, "cpu"),
    }
    out_p = HERE / "valloss.json"
    res = json.loads(out_p.read_text()) if out_p.exists() else {"loss": {}}
    res["scorer"] = {"file": str(VL), "md5": hashlib.md5(VL.read_bytes()).hexdigest()}
    res["n"] = {"val_pairs": sum(len(r) for r in held), "charles_records": len(ch)}
    for name, p in models(vl).items():
        if name in res["loss"] or not p.exists():
            continue
        t0 = time.time()
        m, _, _ = load_ckpt(p, "cpu")
        row = {"ckpt": str(p)}
        for sname, vd in sets.items():
            for k, v in vl.score(m, vd, tok).items():
                row[f"{sname}_{k}"] = v
        res["loss"][name] = row
        out_p.write_text(json.dumps(res, indent=1))
        print(f"{name}: val w1 {row['val_w1']:.4f} ({time.time() - t0:.0f}s)", flush=True)
    lines = [
        "# Teacher-forced loss (generated by `valloss.py`; cpt_control's scorer, CPU fp32)",
        "",
        f"Stage 1 val split ({res['n']['val_pairs']} pairs) and Charles149 reference proofs "
        f"({res['n']['charles_records']} records). Mean NLL per scored token; "
        "S1g3_s0 logged 0.0692.",
        "",
        "| model | val w1 | val w0 | Charles149 ref w1 | Charles149 ref w0 |",
        "|---|---|---|---|---|",
    ]
    for k in models(vl):
        r = res["loss"].get(k)
        if r:
            lines.append(
                f"| {k} | {r['val_w1']:.4f} | {r['val_w0']:.4f} | {r['charles_ref_w1']:.4f} "
                f"| {r['charles_ref_w0']:.4f} |"
            )
    (HERE / "valloss.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
