#!/usr/bin/env python3
"""Fake finishes (CPU only): failed samples whose first rejected line writes the theorem's own conclusion.

    python fake_finish.py [--procs 12]

For every evaluated checkpoint (eval/<label>/) and every standard (L6-18) and matched (L6-14) unit, each saved sample
(samples/<unit>.jsonl.gz) is re-classified with ndcheck.classify. A failed sample is a *fake finish* when its first
rejected line (kind bad_line) states the prompted conclusion, i.e. the model writes the goal with an invalid step.
Per arm (seeds pooled) x set x length: share of failed samples that are fake finishes, median line position of the
fake line, and share of fake finishes written at a position below L_true. Writes report/fake_finish.json and
report/fake_finish.md.
"""
import argparse, collections, gzip, json, os, sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import EVAL, REPORT, TESTSETS, read_jsonl, write_json  # noqa: E402
from ndcheck import classify, sequent  # noqa: E402

PROMPTS = {}


def goal_of(prompt):
    t = prompt.split()
    return ' '.join(t[t.index('SEQ') + 1:t.index('PRF')])


def line_formula(toks):
    i = 1 if toks and toks[0].startswith('N') and toks[0][1:].isdigit() else 0
    while i < len(toks) and toks[i] == '|':
        i += 1
    j = toks.index(':') if ':' in toks[i:] else len(toks) - 1
    return ' '.join(toks[i:j]), toks[1:i].count('|') if i > 1 else 0


def work(args):
    label, unit = args
    fn = os.path.join(EVAL, label, 'samples', f'{unit}.jsonl.gz')
    s, _, L = unit.rpartition('_L')
    L = int(L)
    n = nf = nfake = below = 0
    pos = []
    seqs = {}
    with gzip.open(fn, 'rt') as f:
        for line in f:
            r = json.loads(line)
            p = PROMPTS[r['name']]
            if p not in seqs:
                seqs[p] = sequent(p)
            c = classify(p, r['body'], seqs[p])
            n += 1
            if c['ok']:
                continue
            nf += 1
            if c['kind'] != 'bad_line':
                continue
            toks = r['body'].split()
            if 'QED' in toks:
                toks = toks[:toks.index('QED')]
            lines, cur = [], []
            for t in toks:
                cur.append(t)
                if t == ';':
                    lines.append(cur); cur = []
            k = c['line'] - 1
            off = lines[k] if k < len(lines) else cur
            f_, _ = line_formula(off)
            if f_ == goal_of(p):
                nfake += 1
                pos.append(c['line'])
                below += c['line'] < L
    return label, s, L, n, nf, nfake, below, pos


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--procs', type=int, default=12)
    a = ap.parse_args()
    for f in ('std.jsonl', 'matched.jsonl'):
        for r in read_jsonl(os.path.join(TESTSETS, f)):
            PROMPTS[r['name']] = r['prompt']
    tasks = []
    for label in sorted(os.listdir(EVAL)):
        sd = os.path.join(EVAL, label, 'samples')
        if os.path.isdir(sd):
            tasks += [(label, fn[:-len('.jsonl.gz')]) for fn in sorted(os.listdir(sd)) if fn.endswith('.jsonl.gz')]
    agg = collections.defaultdict(lambda: [0, 0, 0, 0, []])
    with Pool(a.procs) as pool:
        for label, s, L, n, nf, nfake, below, pos in pool.imap_unordered(work, tasks):
            arm = 'pretrain' if label == 'pretrain' else label.split('_s')[0]
            g = agg[(arm, s, L)]
            g[0] += n; g[1] += nf; g[2] += nfake; g[3] += below; g[4] += pos
    out = {}
    for (arm, s, L), (n, nf, nfake, below, pos) in sorted(agg.items()):
        pos.sort()
        out[f'{arm}|{s}|{L}'] = {'samples': n, 'failed': nf, 'fake': nfake, 'fake_share_of_failed': nfake / nf if nf else None,
                                 'fake_share_of_samples': nfake / n if n else None,
                                 'fake_median_line': pos[len(pos) // 2] if pos else None,
                                 'fake_below_L_true': below / nfake if nfake else None}
    write_json(os.path.join(REPORT, 'fake_finish.json'), out)
    arms = ['pretrain', 'A', 'B', 'C', 'D']
    md = ['# Fake finishes\n', 'Cell: share of failed samples whose first rejected line writes the theorem\'s conclusion / median line '
          'position of that line (seeds pooled). Generated by `fake_finish.py` from the saved samples.\n']
    for s in ('std', 'matched'):
        Ls = sorted({L for (a_, s_, L) in agg if s_ == s})
        md.append(f'\n**{s}**\n\n| arm | ' + ' | '.join(f'L{L}' for L in Ls) + ' |\n|' + '---|' * (len(Ls) + 1))
        for arm in arms:
            cells = []
            for L in Ls:
                v = out.get(f'{arm}|{s}|{L}')
                cells.append(f"{100 * v['fake_share_of_failed']:.0f}% / {v['fake_median_line']}" if v and v['fake_share_of_failed'] is not None and v['fake'] else ('0%' if v else ''))
            md.append(f'| {arm} | ' + ' | '.join(cells) + ' |')
    with open(os.path.join(REPORT, 'fake_finish.md'), 'w') as f:
        f.write('\n'.join(md) + '\n')
    print('wrote', os.path.join(REPORT, 'fake_finish.json'), len(out), 'cells')


if __name__ == '__main__':
    main()
