#!/usr/bin/env bash
# finalize.sh <alias> <run> <tag>: after the run has logged RL_DONE, on the run's own pod:
#   1. pull the run to serrano and pick the policy checkpoint by the rule (report.py --best:
#      highest dev plain pass@1 among the scored rounds, ties to the later round);
#   2. train the run's two verifier networks on the step data of all its rounds;
#   3. pack policy + verifier networks + the frozen solver settings ($F/final/solver.json) into
#      /workspace/final/final_<tag>.pt;
#   4. score it on dev in plain and full mode (5 draws, seed 0, Lean-judged), and the run's
#      pretrained base in plain mode with the same solver code;
#   5. copy the packed checkpoint, dev rows and logs to $F/final/<tag>/ and compare md5.
# The remote part runs detached on the pod (a dropped ssh connection does not stop it); this
# script polls for its end. DISC_STEPS and MSLOT_STEPS shorten the verifier trainings for a dry
# run. With VERIFIER=none (the ablation: it saved no step data) the checkpoint is packed without
# a verifier and scored in plain mode only.
set -uo pipefail
h=$1; run=$2; tag=$3
F=/scratch/cowifornia/nd-rl/fable_rl
HERE=$(cd "$(dirname "$0")" && pwd)
SSH=(ssh -n -F $F/ssh_config)
mkdir -p $F/final/$tag
timeout 60 "${SSH[@]}" "$h" "grep -q RL_DONE /workspace/runs/$run.log" || { echo "no RL_DONE in $run.log on $h"; exit 1; }
bash "$HERE/pull.sh" "$h" | tail -1
D=$F/runs/$h/$run
python3 "$HERE/../report.py" --best "$D" > $F/final/$tag/checkpoint_rule.txt
rnd=$(grep -o 'picked round [0-9]*' $F/final/$tag/checkpoint_rule.txt | grep -o '[0-9]*')
[[ -n $rnd ]] || { echo "no checkpoint picked for $tag"; exit 1; }
echo "$tag: rule picks r$rnd.pt"
bash "$HERE/push.sh" "$h" | tail -1
R=/workspace/runs/$run
X=/workspace/data/train_k12.jsonl.gz
cat > $F/final/$tag/remote_$tag.sh <<REMOTE
#!/usr/bin/env bash
# generated by finalize.sh for $tag (run $run on $h), policy r$rnd
PY=/workspace/venv/bin/python
export PYTHONUNBUFFERED=1 LEAN_GATE_WORKERS=7
mkdir -p /workspace/final && cd /workspace/fr
if [ "${VERIFIER:-two}" = none ]; then
  modes="plain"
  \$PY pack.py --policy $R/r$rnd.pt --out /workspace/final/final_$tag.pt --solver "\$(cat /workspace/final/solver.json)" --note "$tag: policy r$rnd of $run, no verifier" > /workspace/final/pack_$tag.log 2>&1
else
  modes="plain full"
  timeout 3000 \$PY -m fr.verifier --kind disc --run $R --out $R/verifier_disc.pt --x $X --steps ${DISC_STEPS:-6000} --max_per_round 150000 --x_pos 400000 > /workspace/final/verifier_disc_$tag.log 2>&1
  timeout 6000 \$PY -m fr.verifier --kind mslot --run $R --out $R/verifier_mslot.pt --x $X --steps ${MSLOT_STEPS:-8000} --n_layer 6 --d 384 --x_pos 1200000 > /workspace/final/verifier_mslot_$tag.log 2>&1
  \$PY pack.py --policy $R/r$rnd.pt --verifier $R/verifier_mslot.pt:$(cat $F/final/thr_mslot),$R/verifier_disc.pt:$(cat $F/final/thr_disc) --out /workspace/final/final_$tag.pt --solver "\$(cat /workspace/final/solver.json)" --note "$tag: policy r$rnd of $run, verifier networks from all its rounds" > /workspace/final/pack_$tag.log 2>&1
fi
for m in \$modes; do
  SOLVER_MODE=\$m timeout 2400 \$PY solve.py --ckpt /workspace/final/final_$tag.pt --in /workspace/data/y_dev.jsonl --out /workspace/final/dev_${tag}_\$m.jsonl --k 5 --seed 0 --judge 2>&1 | grep -v Warn > /workspace/final/dev_${tag}_\$m.log
done
init=\$(grep -o '"init": "[^"]*"' $R/rl.log | head -1 | cut -d'"' -f4)
if [ -f "\$init" ]; then
  SOLVER_MODE=plain timeout 1200 \$PY solve.py --ckpt \$init --in /workspace/data/y_dev.jsonl --out /workspace/final/dev_base_${tag}_plain.jsonl --k 5 --seed 0 --temperature $(python3 -c "import json;print(json.load(open('$F/final/solver.json'))['plain'].get('temperature',1.0))") --judge 2>&1 | grep -v Warn > /workspace/final/dev_base_${tag}_plain.log
fi
cd /workspace/final && md5sum final_$tag.pt dev_*${tag}_*.jsonl > md5_$tag.txt
echo FINAL_DONE > /workspace/final/done_$tag
REMOTE
rsync -t -e "ssh -F $F/ssh_config" $F/final/solver.json $F/final/$tag/remote_$tag.sh "$h:/workspace/final/" || { timeout 60 "${SSH[@]}" "$h" "mkdir -p /workspace/final"; rsync -t -e "ssh -F $F/ssh_config" $F/final/solver.json $F/final/$tag/remote_$tag.sh "$h:/workspace/final/"; }
timeout 60 "${SSH[@]}" "$h" "rm -f /workspace/final/done_$tag; chmod +x /workspace/final/remote_$tag.sh; nohup /workspace/final/remote_$tag.sh > /workspace/final/remote_$tag.log 2>&1 < /dev/null & echo launched $tag on $h"
t0=$(date +%s)
until timeout 30 "${SSH[@]}" "$h" "test -f /workspace/final/done_$tag" 2>/dev/null; do
  sleep 60
  if (( $(date +%s) - t0 > ${FINALIZE_TIMEOUT:-9000} )); then echo "FINALIZE_TIMEOUT $tag"; exit 2; fi
done
timeout 60 "${SSH[@]}" "$h" "grep -h 'examples\|^holdout' /workspace/final/verifier_*_$tag.log 2>/dev/null | cut -c1-400; cat /workspace/final/pack_$tag.log | grep -v Warn | cut -c1-300; for f in /workspace/final/dev_*${tag}_*.log; do echo \"== \$f\"; grep '^all\|^src' \$f; done"
for i in 1 2 3; do timeout 1500 rsync -rlpt -e "ssh -F $F/ssh_config" "$h:/workspace/final/" $F/final/$tag/ && break; sleep 20; done
(cd $F/final/$tag && md5sum -c md5_$tag.txt | tr '\n' ' ')
echo "FINALIZE_OK $tag r$rnd $(date -u +%FT%TZ)"
