#!/usr/bin/env python3
"""Autoresearch-style log for the combined-pipeline series (agent `claude-manual`).

  results.py new <cNNN> <slug> <arm> <run>  # results/<cNNN>-claude-manual_<slug>/params.json with
                                            # the mechanical fields filled and TODOs for the rest;
                                            # fill them and commit BEFORE launching
  results.py record <cNNN>-claude-manual_<slug> keep|discard|crash "surprise"
                                            # merges artifacts/autoresearch/<run>_s<seed>/
                                            # summary.json into results.json, refreshes RESULTS.md

Same keep rule as the pretrain loop: 3-seed mean `metric` (dev transfer solved at L_true >= 7,
EVAL_K 64) strictly above the incumbent's. Separate from the loop's results/ because the RL stage
differs, so these numbers must not enter its leaderboard.
"""

import hashlib
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
ART = os.path.join(HERE, "..", "..", "..", "..", "artifacts", "autoresearch")
AGENT, MODEL, SEEDS = "claude-manual", "claude-opus-5-5", [0, 1, 2]
ARM_FILES = {  # the files that define each arm, hashed into params.json
    "ei": ["ckpt_shim.py", "launch.py"],
    "leon": ["ckpt_shim.py", "launch.py", "leon_rl.py", "harness_leon.py", "fast_sample.py"],
}
TODO = "TODO"


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()[:12]


def new(cid, slug, arm, run_prefix):
    d = os.path.join(RES, f"{cid}-{AGENT}_{slug}")
    os.makedirs(d)
    commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], text=True).strip()
    p = {
        "id": f"{cid}-{AGENT}",
        "slug": slug,
        "arm": arm,
        "run_prefix": run_prefix,  # pod runs are <run_prefix>_s<seed>
        "written_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "base_commit": commit,
        "provider": "anthropic",
        "model": MODEL,
        "files": {f: sha(os.path.join(HERE, f)) for f in ARM_FILES[arm]},
        "harness_sha": sha(os.path.join(HERE, "..", "autoresearch", "harness.py")),
        "pretrain": "186-claude pretrain.pt per seed (pretrain_sha fc09860cd285)",
        "seeds": SEEDS,
        "title": TODO,
        "description": TODO,
        "tags": [TODO],
        "hypothesis": TODO,
        "p_keep": TODO,
        "expected_delta": TODO,
        "baseline_id": TODO,
        "baseline_metric": TODO,
        "config": TODO,
    }
    with open(os.path.join(d, "params.json"), "w") as f:
        json.dump(p, f, indent=1)
    print(d)


def record(name, status, surprise):
    d = os.path.join(RES, name)
    with open(os.path.join(d, "params.json")) as f:
        p = json.load(f)
    assert TODO not in json.dumps(p), "params.json still has TODOs"
    assert not os.path.exists(os.path.join(d, "results.json")), "already recorded"
    seeds = {}
    for s in p["seeds"]:
        fn = os.path.join(ART, f"{p['run_prefix']}_s{s}", "summary.json")
        with open(fn) as f:
            seeds[s] = json.load(f)
    ok = [s for s in seeds if seeds[s]["status"] == "ok"]
    mean = lambda xs: sum(xs) / len(xs) if xs else None  # noqa: E731
    r = {
        "recorded_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "status": status,
        "metric": mean([seeds[s]["metric"] for s in ok]) if len(ok) == len(seeds) else None,
        "seed_metrics": {str(s): seeds[s]["metric"] for s in seeds},
        "metric_rl": mean([seeds[s]["metric_rl"] for s in ok]),
        "seed_status": {str(s): seeds[s]["status"] for s in seeds},
        "total_secs": {str(s): round(seeds[s]["total_secs"]) for s in seeds},
        "rl_secs": {str(s): round(seeds[s].get("rl", {}).get("secs", 0)) for s in seeds},
        "gpu": {str(s): seeds[s]["gpu"] for s in seeds},
        "eval": {
            str(s): {k: seeds[s].get("eval", {}).get(k) for k in ("solved", "ge", "lstar")}
            for s in seeds
        },
        "rl_rounds": {
            str(s): [
                {
                    k: x.get(k)
                    for k in (
                        "round",
                        "sample_acc",
                        "new_proofs",
                        "targets_solved",
                        "lstar",
                        "secs",
                    )
                }
                for x in seeds[s].get("rl", {}).get("rounds", [])
            ]
            for s in seeds
        },
        "surprise": surprise,
    }
    with open(os.path.join(d, "results.json"), "w") as f:
        json.dump(r, f, indent=1)
    table()


def table():
    rows = [
        "# Combined-pipeline results (agent claude-manual; generated by results.py)",
        "",
        "| id | title | baseline | p_keep | metric | seeds | RL solved | total s | status "
        "| surprise |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in sorted(os.listdir(RES)):
        d = os.path.join(RES, name)
        if not os.path.isdir(d):
            continue
        with open(os.path.join(d, "params.json")) as f:
            p = json.load(f)
        r = {}
        if os.path.exists(os.path.join(d, "results.json")):
            with open(os.path.join(d, "results.json")) as f:
                r = json.load(f)
        m = r.get("metric")
        rows.append(
            f"| {p['id']} | {p['title']} | {p['baseline_id']} | {p['p_keep']} "
            f"| {'' if m is None else round(m, 1)} "
            f"| {'/'.join(str(v) for v in r.get('seed_metrics', {}).values())} "
            f"| {'' if r.get('metric_rl') is None else round(r['metric_rl'])} "
            f"| {'/'.join(str(v) for v in r.get('total_secs', {}).values())} "
            f"| {r.get('status', 'running')} | {r.get('surprise', '')} |"
        )
    with open(os.path.join(HERE, "RESULTS.md"), "w") as f:
        f.write("\n".join(rows) + "\n")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "table"
    if cmd == "new":
        new(*sys.argv[2:6])
    elif cmd == "record":
        record(*sys.argv[2:5])
    else:
        table()
