"""The low-RL arm on the 13-20-line subset (250 problems, k512, seed 0): RL - base at k1 and k512.

The same checkpoints as the teaser's panel (b), on the long-proof sample in sets/t1320s250_ids.txt.
Run from the repo root:
    ND_OFFLINE=1 PYTHONDONTWRITEBYTECODE=1 code/.venv/bin/python -m \\
        code.experiments.current.high_rl_passk_20261030.lowrl_1320
Prints the table and writes lowrl_1320.md / .json next to this file.
"""

import csv
import json
from pathlib import Path

from code.thinking import stats

HERE = Path(__file__).parent
V2 = Path("/scratch/cowifornia/nd-rl/think/runs/eval/v2")
K = 512


def load(stem: str) -> stats.Arm:
    d = V2 / f"t1320s250_{stem}_s0_plain_k{K}"
    assert (d / "summary.json").exists(), d
    a = stats.load_arm(stem, [d / "rows_plain_B64.jsonl"])
    assert len(a.names) == 250 and a.kmax >= K, (stem, len(a.names), a.kmax)
    return a


with open(HERE / "lowrl_compute.tsv") as f:
    R = {r["checkpoint"]: float(r["R"]) for r in csv.DictReader(f, delimiter="\t")}
base = load("s1g3")
stems = sorted(
    (
        d.name[len("t1320s250_") : -len(f"_s0_plain_k{K}")]
        for d in V2.glob(f"t1320s250_*_s0_plain_k{K}")
    ),
    key=lambda s: R.get(s, -1.0),
)
rows = []
for stem in stems:
    if stem == "s1g3":
        continue
    a = load(stem)
    assert a.names == base.names
    g1 = stats.paired_diff(a, base, 1, draws=4000)
    gK = stats.paired_diff(a, base, K, draws=4000)
    rows.append(
        {
            "checkpoint": stem,
            "R": R[stem],
            "pass@1": 100 * a.values(1).mean(),
            "pass@5": 100 * a.values(5).mean(),
            f"pass@{K}": 100 * a.values(K).mean(),
            "gap1": [100 * g1.est, 100 * g1.lo, 100 * g1.hi],
            f"gap{K}": [100 * gK.est, 100 * gK.lo, 100 * gK.hi],
        }
    )

b1, b5, bK = (100 * base.values(k).mean() for k in (1, 5, K))
lines = [
    "# Low-RL arm on the 13-20-line subset (generated by `lowrl_1320.py`)",
    "",
    f"Base S1g3_s0: pass@1 {b1:.1f}, pass@5 {b5:.1f}, pass@{K} {bK:.1f} (% of 250).",
    "Gaps in points, 95% problem-bootstrap intervals.",
    "",
    f"| checkpoint | R | pass@1 | pass@5 | pass@{K} | gap pass@1 [95%] | gap pass@{K} [95%] |",
    "| --- | --- | --- | --- | --- | --- | --- |",
]
for r in rows:
    c1, cK = r["gap1"], r[f"gap{K}"]
    lines.append(
        f"| {r['checkpoint'].removeprefix('grpo_think_vs_')} | {r['R']:.3g} | {r['pass@1']:.1f} | "
        f"{r['pass@5']:.1f} | {r[f'pass@{K}']:.1f} | {c1[0]:+.1f} [{c1[1]:+.1f}, {c1[2]:+.1f}] | "
        f"{cK[0]:+.1f} [{cK[1]:+.1f}, {cK[2]:+.1f}] |"
    )
(HERE / "lowrl_1320.md").write_text("\n".join(lines) + "\n")
(HERE / "lowrl_1320.json").write_text(json.dumps({"base": [b1, b5, bK], "rows": rows}, indent=1))
print("\n".join(lines))
