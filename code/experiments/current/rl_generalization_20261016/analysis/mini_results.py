def drift(ld: Loader, arms: dict, ref_seeds: list[int], s_ref: float) -> list[str]:
    """§ 6: a later reference seed's 13–20 logit against the s0–s3 range ± 3 s_ref."""
    extra = [s for s in with_reads(ld, REF, arms[REF], "t1320") if s not in REF_SEEDS]
    xr = x_of(ld, REF, ref_seeds, *PRIMARY) if ref_seeds else None
    if not extra or not xr:
        return []
    md = ["", "### Drift check (§ 6): later reference seeds", ""]
    for s in extra:
        x = (x_of(ld, REF, [s], *PRIMARY) or [float("nan")])[0]
        out = x < min(xr) - 3 * s_ref or x > max(xr) + 3 * s_ref
        md.append(
            f"- s{s}: 13–20 x {lg(x)} against the s0–s3 range [{lg(min(xr))}, {lg(max(xr))}] "
            f"± 3 s_ref: {'OUTSIDE: re-examine the knob comparisons' if out else 'inside'}."
        )
    return md


def run_table(runs: dict, arms: dict) -> list[str]:
    md = [
        "| run | seed | code | status | L2: it / rollbacks / lr_scale | "
        "L3: it / rollbacks / lr_scale | reads (of 5) | flags |",
        "|---|---|---|---|---|---|---|---|",
    ]

    def st(s: Stage | None) -> str:
        if s is None:
            return "reference's"
        if not s.exists:
            return "—"
        rb = "?" if s.rollbacks is None else str(s.rollbacks)
        lr = "?" if s.lr_scale is None else f"{s.lr_scale:g}"
        extra = f" ({s.rows} rows, {s.restarts} rerun)" if s.restarts else ""
        return f"{s.iters}/{ITERS} / {rb} / {lr}{extra}{'' if s.final else ', no _it10.pt'}"

    for arm, seeds in arms.items():
        for s in seeds if arm != BASE else ():
            r = runs[(arm, s)]
            md.append(
                f"| {label(arm)} | {s} | {r.commit or '—'} | {r.status()} | "
                f"{st(r.stages.get('L2'))} | {st(r.stages['L3'])} | {sum(r.reads.values())} | "
                f"{r.flags()} |"
            )
    md.append("")
    rs = list(runs.values())
    alarms = [(r, x) for r in rs for s in r.stages.values() for x in s.alarms]
    fails = [(r, x) for r in rs for s in r.stages.values() for x in s.failed]
    fails += [(r, x) for r in rs for x in r.line_failed]
    fails += [
        (r, f"(earlier attempt) {x}")
        for r in rs
        for s in r.stages.values()
        for x in s.failed_before
    ]
    md += [f"- ALARM {label(r.arm)} s{r.seed}: `{x.strip()}`" for r, x in alarms] or [
        "- No ALARM lines."
    ]
    md += [f"- FAILED {label(r.arm)} s{r.seed}: `{x.strip()}`" for r, x in fails] or [
        "- No FAILED lines."
    ]
    for r in rs:
        init = r.stages["L3"].init
        if r.fork and init:
            want = str(GV / f"{REF}_s{r.seed}_L2" / "ckpts" / f"{REF}_s{r.seed}_L2_it{ITERS}.pt")
            note = "the reference's L2-mini at its seed" if init == want else "NOT the reference's"
            md.append(f"- {label(r.arm)} s{r.seed} forks from `{Path(init).name}` ({note}).")
    return md


def idood_table(ld: Loader, arms: dict, ref_seeds: list[int]) -> list[str]:
    """§ 4.1 / § 4.3 without trajectories: each arm's Δlogit on the ID and OOD sets."""
    df = max(len(ref_seeds) - 1, 1)
    t975 = stats.t_ppf(0.975, df)
    md = [
        "",
        "## Competence versus generalization (§ 4.3)",
        "",
        "Each arm's seed-mean logit minus the references' (pass@1); ID = L2 / L3 test_1k, OOD =",
        "the rest. Interval: Δ ± t(0.975, n_r − 1) · s_ref(metric) · √(1/n + 1/n_r), the noise of",
        "the references' own spread on that metric (§ 6).",
        "",
        "| arm | seeds | " + " | ".join(SUB[s].title for s in SUB) + " |",
        "|---|---|" + "---|" * len(SUB),
    ]
    for arm, seeds in arms.items():
        if arm in (REF, BASE) or not with_reads(ld, arm, seeds, "t1320"):
            continue
        cells = []
        for sub in SUB:
            have = with_reads(ld, arm, seeds, sub)
            xc = x_of(ld, arm, have, sub, 1) if have else None
            xr = x_of(ld, REF, ref_seeds, sub, 1)
            if not xc or not xr or len(xr) < 2:
                cells.append("—")
                continue
            d = mean(xc) - mean(xr)
            h = t975 * sd(xr) * math.sqrt(1 / len(xc) + 1 / len(xr))
            cells.append(f"{lg(d)} [{d - h:+.3f}, {d + h:+.3f}]")
        used = with_reads(ld, arm, seeds, "t1320")
        md.append(f"| {label(arm)} | {seeds_str(used)} | " + " | ".join(cells) + " |")
    return md


def missing_md(ld: Loader) -> list[str]:
    miss = sorted(set(ld.missing))
    if not miss:
        return ["", "## Missing reads", "", "None of the planned reads is missing."]
    by: dict[str, list[str]] = {}
    for p in miss:
        by.setdefault(v2._run_of(p), []).append(Path(p).parent.name)
    mini = {r: d for r, d in by.items() if r.startswith(REF)}
    full = {r: d for r, d in by.items() if not r.startswith(REF)}
    md = ["", "## Missing reads (planned, not there yet)", ""]
    for title, part in (("Mini runs", mini), ("G3's full-scale ckreads", full)):
        if part:
            md += [f"{title}:", ""]
            md += [f"- `{r}`: {', '.join(f'`{x}`' for x in d)}" for r, d in sorted(part.items())]
            md.append("")
    return md[:-1]


def table_md(ld: Loader, est: Est, arms: dict[str, tuple[int, ...]], runs: dict) -> list[str]:
    head = "| " + " | ".join(SUB[s].title for s in SUB) + " |"
    md = [
        "# Mini runs: pass@1 / pass@5 per arm and seed",
        "",
        f"{HEADER} {now_line()}",
        "",
        "pass@1 / pass@5 in % of the set: unbiased estimators from each read's k attempts",
        "(MINI_READS: k8; Charles149 k64), plain reads at B64 and T 0.8 of L3-mini's last",
        "checkpoint (the base: S1g3_s0). Per run: 95% problem bootstrap; pooled: hierarchical",
        "bootstrap over seeds and problems; differences: paired on problems. The gate:",
        "[gate.md](gate.md).",
        "",
        "## 1. Per run",
        "",
        "| arm | seed | flags " + head,
        "|---|---|---|" + "---|" * len(SUB),
    ]
    for arm, seeds in arms.items():
        for s in seeds:
            cells = [cell(est.ci(arm, sub, (s,), 1), est.ci(arm, sub, (s,), 5)) for sub in SUB]
            fl = "—" if arm == BASE else runs[(arm, s)].flags()
            md.append(f"| {label(arm)} | {s} | {fl} | " + " | ".join(cells) + " |")
    md += ["", "## 2. Pooled over seeds", "", "| arm | seeds " + head]
    md.append("|---|---|" + "---|" * len(SUB))
    for arm, seeds in arms.items():
        cells, used = [], set()
        for sub in SUB:
            have = tuple(with_reads(ld, arm, seeds, sub))
            used |= set(have)
            cells.append(
                cell(est.ci(arm, sub, have, 1), est.ci(arm, sub, have, 5)) if have else "—"
            )
        if used:
            md.append(f"| {label(arm)} | {seeds_str(sorted(used))} | " + " | ".join(cells) + " |")
    md += [
        "",
        "## 3. Differences against the reference (points: Δ pass@1 / Δ pass@5)",
        "",
        "Seed-matched: the arm at seed s − the reference at seed s (for a fork, the same L2-mini);",
        "pooled: over the matched seeds, seeds paired. The base row is the reference (s0–s3) − the",
        "base: what the 10 + 10 iterations buy.",
        "",
        "| comparison | seeds " + head,
        "|---|---|" + "---|" * len(SUB),
    ]
    rs = tuple(with_reads(ld, REF, REF_SEEDS, "t1320"))
    if rs:
        cells = [
            cell(est.diff(REF, rs, BASE, (0,), sub, 1), est.diff(REF, rs, BASE, (0,), sub, 5), True)
            for sub in SUB
        ]
        md.append(f"| reference − base | {seeds_str(rs)} vs 0 | " + " | ".join(cells) + " |")
    for arm, seeds in arms.items():
        if arm in (REF, BASE):
            continue
        for g in [(s,) for s in seeds] + ([tuple(seeds)] if len(seeds) > 1 else []):
            cells = []
            for sub in SUB:
                gs = tuple(
                    s for s in with_reads(ld, arm, g, sub) if s in with_reads(ld, REF, g, sub)
                )
                ok = gs and (len(g) == 1 or len(gs) > 1)
                d1 = est.diff(arm, gs, REF, gs, sub, 1) if ok else None
                d5 = est.diff(arm, gs, REF, gs, sub, 5) if ok else None
                cells.append(cell(d1, d5, True))
            if any(c != "—" for c in cells):
                md.append(
                    f"| {label(arm)} − reference | {seeds_str(g)} | " + " | ".join(cells) + " |"
                )
    md += [
        "",
        "## 4. Run-level logits x_r (the gate's inputs)",
        "",
        "| arm | seed | " + " | ".join(f"{SUB[s].title} p@1 / p@5" for s in SUB) + " |",
        "|---|---|" + "---|" * len(SUB),
    ]
    for arm, seeds in arms.items():
        for s in seeds:
            cells = []
            for sub in SUB:
                p1, p5 = p_of(ld, arm, sub, s, 1), p_of(ld, arm, sub, s, 5)
                ok = p1 is not None and p5 is not None
                cells.append(f"{lg(logit(p1))} / {lg(logit(p5))}" if ok else "—")
            if any(c != "—" for c in cells):
                md.append(f"| {label(arm)} | {s} | " + " | ".join(cells) + " |")
    md += missing_md(ld)
    return md


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    ap.add_argument("--draws", type=int, default=stats.DRAWS)
    ap.add_argument("--v2", default=str(R / "eval/v2"), help="the v2 reads (a copy for tests)")
    ap.add_argument("--out", default=str(STUDY / "results"))
    a = ap.parse_args(argv)
    ev = Path(a.v2)
    arms, keep = register(discover(ev))
    order = [BASE, REF, *(c.arm for c in CONTROLS)]
    arms = {k: arms[k] for k in order + sorted(set(arms) - set(order))}
    ld = Loader(ev, keep)
    est = Est(ld, a.draws)
    runs = {
        (arm, s): run_info(ld, arm, s) for arm, seeds in arms.items() if arm != BASE for s in seeds
    }
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    g = gate_md(ld, est, arms, runs)
    (out / "gate.md").write_text("\n".join(g) + "\n")
    t = table_md(ld, est, arms, runs)
    (out / "mini_table.md").write_text("\n".join(t) + "\n")
    print("\n".join(x for x in g if x.startswith("- **")))
    print(f"wrote {out / 'gate.md'}, {out / 'mini_table.md'}; {len(set(ld.missing))} reads missing")
    return 0


