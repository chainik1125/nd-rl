def main():
    src = open(RL_C).read()
    assert src.startswith('"""'), 'rl_C.py must start with its docstring'
    out = src
    for a, b in EDITS:
        if out.count(a) != 1:
            raise SystemExit(f'rl edit does not apply exactly once ({out.count(a)}x): {a[:80]!r}')
        out = out.replace(a, b)
    out = HEADER + out[3:]
    dst = os.path.join(HERE, 'rl_goals.py')
    open(dst, 'w').write(out)
    diff = difflib.unified_diff(src.splitlines(), out.splitlines(), 'lengthexp/rl_C.py', 'rl_goals.py', lineterm='', n=1)
    open(os.path.join(HERE, 'rl_goals.diff'), 'w').write(f'# rl_C.py sha256 {sha256_file(RL_C)}\n' + '\n'.join(diff) + '\n')
    print('wrote', dst, 'sha256', sha256_file(dst))


if __name__ == '__main__':
    main()
