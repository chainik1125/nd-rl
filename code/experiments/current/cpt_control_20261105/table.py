"""CPT control table (PREREG): base S1g3 vs CPT vs the L3 end on Charles149 at k1024, seeds paired.

    ND_OFFLINE=1 PYTHONDONTWRITEBYTECODE=1 python -m \
        code.experiments.current.cpt_control_20261105.table

Reads /scratch/cowifornia/nd-rl/think/runs/eval/v2/charles149_{s1g3,cpt_s1g3,grpo_think_vs_mb_kkl0}
_s<seed>_plain_k1024/rows_plain_B64.jsonl (the 149 Charles149 problems, as seeds3.py). Writes
table.json and table.md next to this file.
"""

from __future__ import annotations

import json
from pathlib import Path

from code.thinking import stats

V2 = Path("/scratch/cowifornia/nd-rl/think/runs/eval/v2")
KEEP_FILE = Path("/scratch/cowifornia/nd-rl/think/runs/pools/charles_1002/charles_clean.jsonl")
HERE = Path(__file__).resolve().parent
KS = [1, 5, 64, 1024]
N = 1024
ARMS = {"base": "s1g3", "cpt": "cpt_s1g3", "rl": "grpo_think_vs_mb_kkl0"}
keep = {json.loads(x)["name"] for x in KEEP_FILE.read_text().splitlines() if x.strip()}


def p(stem: str, s: int) -> Path:
    return V2 / f"charles149_{stem}_s{s}_plain_k1024" / "rows_plain_B64.jsonl"


def arm(stem: str, seeds: list[int]) -> stats.Arm:
    a = stats.load_arm(stem, [p(stem, s) for s in seeds])
    a = a.subset(sorted(keep & set(a.names)), stem)
    assert len(a.names) == len(keep) == 149 and a.kmax >= N, (stem, len(a.names), a.kmax)
    return a


def ok_lists(path: Path) -> dict[str, list[int]]:
    out = {}
    for line in path.read_text().splitlines():
        r = json.loads(line)
        if r["name"] in keep:
            out[r["name"]] = r["ok"]
    return out


def main() -> int:
    seeds_have = [s for s in range(3) if p(ARMS["cpt"], s).exists()]
    out: dict[str, object] = {"seeds_with_cpt": seeds_have}
    lines = [
        "# CPT control on Charles149 (generated by `table.py`)",
        "",
        "pass@k in % of 149; gaps in points with 95% intervals (stats.paired_diff, seeds paired, "
        "4,000 draws). share = (CPT − base) / (RL − base).",
        "",
        "| seeds | k | base | CPT | RL | CPT − base | RL − CPT | RL − base | share |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    groups = [[s] for s in seeds_have] + ([seeds_have] if len(seeds_have) > 1 else [])
    for seeds in groups:
        b, c, r = (arm(ARMS[x], seeds) for x in ("base", "cpt", "rl"))
        row = {}
        for k in KS:
            vals = {x: 100 * a.values(k).mean() for x, a in (("base", b), ("cpt", c), ("rl", r))}
            d = {}
            for name, (x, y) in {"cpt-base": (c, b), "rl-cpt": (r, c), "rl-base": (r, b)}.items():
                e = stats.paired_diff(x, y, k, paired_seeds=True, draws=4000)
                d[name] = [100 * e.est, 100 * e.lo, 100 * e.hi]
            share = d["cpt-base"][0] / d["rl-base"][0] if d["rl-base"][0] else float("nan")
            row[k] = {**vals, **d, "share": share}

            def f(v: list[float]) -> str:
                return f"{v[0]:+.1f} [{v[1]:+.1f}, {v[2]:+.1f}]"

            lines.append(
                f"| {'+'.join(map(str, seeds))} | {k} | {vals['base']:.1f} | {vals['cpt']:.1f} "
                f"| {vals['rl']:.1f} | {f(d['cpt-base'])} | {f(d['rl-cpt'])} | {f(d['rl-base'])} "
                f"| {100 * share:.0f}% |"
            )
        out["+".join(map(str, seeds))] = row
    lines += ["", "Problems solved at k1024 by one arm only (of 149):", ""]
    lines += [
        "| seeds | RL not CPT | CPT not RL | CPT not base | base not CPT | RL not base |",
        "|---|---|---|---|---|---|",
    ]
    L = {x: {s: ok_lists(p(ARMS[x], s)) for s in seeds_have} for x in ARMS}

    def only(x: str, y: str, seeds: list[int]) -> int:
        sx = {n: sum(sum(L[x][s][n][:N]) for s in seeds) for n in keep}
        sy = {n: sum(sum(L[y][s][n][:N]) for s in seeds) for n in keep}
        return sum(sx[n] > 0 and sy[n] == 0 for n in keep)

    for seeds in groups:
        cnt = {
            f"{x}_not_{y}": only(x, y, seeds)
            for x, y in (
                ("rl", "cpt"),
                ("cpt", "rl"),
                ("cpt", "base"),
                ("base", "cpt"),
                ("rl", "base"),
            )
        }
        out[f"only_{'+'.join(map(str, seeds))}"] = cnt
        lines.append(
            f"| {'+'.join(map(str, seeds))} | " + " | ".join(str(v) for v in cnt.values()) + " |"
        )
    (HERE / "table.json").write_text(json.dumps(out, indent=1))
    (HERE / "table.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
