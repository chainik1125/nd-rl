"""Stage 0c replication check -> /scratch/cowifornia/nd-rl/olmo_elicit/stage0/rep.csv and rep.md.

Our fresh draws (runs/<c>/rep/graded.jsonl: the 218 arm-A prompts x 2 draws, his sampler and grader, new seed) against
his stored arm-A cells at the same checkpoint (olmo-ifcurve: dpo 16 draws per prompt from olmo-ifomega F_dpo_ifb,
s2300 8 from F_s2300_ifb). Per prompt: pass@1 = share of strict passes among the prompt's draws. Difference = mean over
the 218 prompts of (ours - his), with a paired prompt-bootstrap 95 % interval (10,000 resamples, seed 0).
PREREG.md rule: PASS when the interval includes 0 or |difference| < 5 points; else FAIL (stage 2 waits on that pod).
Usage: python analyze_rep.py [--runs .../runs] [--ckpts dpo,s2300]
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import dan_curve as dc
import numpy as np

OE = Path("/scratch/cowifornia/nd-rl/olmo_elicit")


def ours(graded: Path) -> dict[str, list[int]]:
    out: dict[str, list[int]] = {}
    seen = set()
    for ln in open(graded):  # noqa: SIM115
        r = json.loads(ln)
        k = (r["pid"], int(r["chunk"]), int(r["i"]))
        if k in seen:
            continue
        seen.add(k)
        out.setdefault(r["pid"], []).append(int(bool(r["strict"])))
    return out


def compare(
    mine: dict[str, list[int]], his_rows: dc.Rows, ckpt: str, prompts: list[str], reps: int = 10000
) -> dict:
    ps = [p for p in prompts if mine.get(p)]
    a = np.array([np.mean(mine[p]) for p in ps])
    b = np.array([np.mean([x["strict"] for x in his_rows.draws(ckpt, p, "A")]) for p in ps])
    d = a - b
    rng = np.random.default_rng(0)
    idx = rng.integers(0, len(ps), size=(reps, len(ps)))
    bd, ba = d[idx].mean(axis=1), a[idx].mean(axis=1)
    lo, hi = np.percentile(bd, [2.5, 97.5])
    alo, ahi = np.percentile(ba, [2.5, 97.5])
    diff = float(d.mean())
    ok = (lo <= 0 <= hi) or abs(diff) < 0.05
    return {
        "ckpt": ckpt,
        "prompts": len(ps),
        "missing_prompts": len(prompts) - len(ps),
        "our_draws": int(sum(len(mine[p]) for p in ps)),
        "his_draws_per_prompt": dc.N_A.get(ckpt, 8),
        "ours_pass1_pct": round(100 * float(a.mean()), 2),
        "ours_lo95": round(100 * float(alo), 2),
        "ours_hi95": round(100 * float(ahi), 2),
        "his_pass1_pct": round(100 * float(b.mean()), 2),
        "diff_pts": round(100 * diff, 2),
        "diff_lo95": round(100 * float(lo), 2),
        "diff_hi95": round(100 * float(hi), 2),
        "verdict": "PASS"
        if ok and len(ps) == len(prompts)
        else ("PASS (incomplete set)" if ok else "FAIL"),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=str(OE / "runs"))
    ap.add_argument("--ckpts", default="dpo,s2300")
    ap.add_argument("--out", default=str(OE / "stage0" / "rep.csv"))
    a = ap.parse_args()
    his = dc.Rows(dc.DAN / "artifacts" / "olmo_ifcurve" / "rows")
    prompts = dc.arm_a()
    res = []
    for c in a.ckpts.split(","):
        g = Path(a.runs) / c / "rep" / "graded.jsonl"
        if not g.exists():
            print(f"{c}: no {g}")
            continue
        res.append(compare(ours(g), his, c, prompts))
    if not res:
        return
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(res[0]))
        w.writeheader()
        w.writerows(res)
    L = [
        "# Stage 0c: replication draw (generated by analyze_rep.py)",
        "",
        "Strict pass@1 on the 218 arm-A prompts, % of the set. Ours: 2 fresh draws per prompt (his sampler and grader, "
        "new seed); his: his stored arm-A cell. Difference: paired prompt bootstrap, 95 %. Rule (PREREG.md): PASS if the "
        "interval includes 0 or |difference| < 5 points.",
        "",
        "| ckpt | prompts | ours pass@1 [95 %] | his pass@1 (draws / prompt) | ours − his [95 %] | verdict |",
        "|---|---|---|---|---|---|",
    ]
    for r in res:
        L.append(
            f"| {r['ckpt']} | {r['prompts']} | {r['ours_pass1_pct']} [{r['ours_lo95']}, {r['ours_hi95']}] | "
            f"{r['his_pass1_pct']} ({r['his_draws_per_prompt']}) | {r['diff_pts']:+} [{r['diff_lo95']}, {r['diff_hi95']}] | {r['verdict']} |"
        )
    Path(a.out).with_suffix(".md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
