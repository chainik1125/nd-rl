def pct(x: float) -> str:
    return "–" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}"


def diff_pts(a: float, b: float) -> str:
    if any(isinstance(v, float) and math.isnan(v) for v in (a, b)):
        return "–"
    d = 100 * (a - b)
    return "0.0" if abs(d) < 5e-5 else f"{d:+.4f}"


def row_compare() -> tuple[list[tuple], dict]:
    per_job, tot = [], {"rows": 0, "strict": 0, "loose": 0, "rlview": 0}
    for ln in open(S / "regrade" / "jobs.txt"):
        job, sp = ln.split()
        gp = Path(sp.replace("/samples/", "/graded/").replace(".jsonl.gz", ".jsonl"))
        a = {(r["pid"], r["chunk"], r["i"]): r for r in map(json.loads, open(gp))}
        b = {
            (r["pid"], r["chunk"], r["i"]): r
            for r in map(json.loads, open(S / "regrade" / f"{job}.jsonl"))
        }
        keys_ok = a.keys() == b.keys()
        d = {
            f: sum(a[k].get(f) != b[k].get(f) for k in a if k in b)
            for f in ("strict", "loose", "rlview")
        }
        per_job.append((job, len(a), len(b), keys_ok, d["strict"], d["loose"], d["rlview"]))
        tot["rows"] += len(a)
        for f in d:
            tot[f] += d[f]
    return per_job, tot


