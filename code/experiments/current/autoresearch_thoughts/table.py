#!/usr/bin/env python3
"""Regenerate RESULTS.md from results/*/params.json + results.json.   python3 table.py"""

from pathlib import Path

from params import HERE
from schema import Params, Results

HEADER = [
    "id",
    "title",
    "agent",
    "tags",
    "p_keep",
    "budget s/pre/rl",
    "patch",
    "metric",
    "at diag level",
    "RL solved",
    "status",
    "greedy",
    "val loss",
    "solved by oracle call",
    "total s",
    "surprise",
]


def row(d: Path) -> list[object]:
    p = Params.model_validate_json((d / "params.json").read_text())
    rf = d / "results.json"
    r = Results.model_validate_json(rf.read_text()) if rf.exists() else None
    b = p.protocol.budget
    curve = (r.pretrain.curve if r else None) or []
    return [
        p.id,
        p.title,
        p.model,
        ", ".join(p.tags),
        p.p_keep,
        f"{b.total_secs}/{b.pretrain_secs}/{b.rl_secs}",
        p.patch_lines,
        r.metric if r else None,
        r.metric_diag if r else None,
        r.metric_rl if r else None,
        r.status if r else "running",
        r.pretrain.heldout_greedy if r else None,
        f"{curve[-1].val_loss:.4f}" if curve else None,
        " ".join(str(x.targets_solved) for x in r.rl_rounds) if r else "",
        r.total_secs if r else None,
        (r.surprise or "").replace("|", "\\|") if r else "",
    ]


def main() -> None:
    dirs = sorted(d for d in (HERE / "results").iterdir() if d.is_dir() and d.name[:3].isdigit())
    rows = [row(d) for d in dirs]
    out = [
        "# Test-time-thoughts autoresearch results (auto-generated by table.py from results/*/)",
        "",
        "| " + " | ".join(HEADER) + " |",
        "| " + " | ".join("---" for _ in HEADER) + " |",
        *("| " + " | ".join("" if x is None else str(x) for x in r) + " |" for r in rows),
    ]
    (HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
    print(f"{len(rows)} rows -> RESULTS.md")


if __name__ == "__main__":
    main()
