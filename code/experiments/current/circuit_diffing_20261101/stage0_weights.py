"""Stage 0: weight diffing of every RL checkpoint against its own Stage-1 base (CPU).

    python -m code.experiments.current.circuit_diffing_20261101.stage0_weights

Per 2-D matrix (qkv split into q / k / v): relative Frobenius change, effective rank and r90 of
dW, the share of dW energy inside the base's top-10% singular subspaces (two- and one-sided, with
the random expectations), and update sparsity. Writes `stage0.json` (per checkpoint and matrix) and
`stage0.md` (medians per checkpoint), then the figure `figs/stage0_weights.{pdf,png}`.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np
import torch

from .common import HERE, registry, state_dict

KFRAC = 0.10


def matrices(sd: dict[str, torch.Tensor]) -> dict[str, torch.Tensor]:
    out = {"emb": sd["emb.weight"], "head": sd["head.weight"]}
    i = 0
    while f"blocks.{i}.qkv.weight" in sd:
        q, k, v = sd[f"blocks.{i}.qkv.weight"].chunk(3, 0)
        out.update({f"b{i}.q": q, f"b{i}.k": k, f"b{i}.v": v})
        for n in ("proj", "fc1", "fc2"):
            out[f"b{i}.{n}"] = sd[f"blocks.{i}.{n}.weight"]
        i += 1
    return out


def metrics(w0: torch.Tensor, dw: torch.Tensor, base_svd: tuple[torch.Tensor, ...]) -> dict:
    w0, dw = w0.double(), dw.double()
    n, m = dw.shape
    e = float((dw**2).sum())
    out = {"rel": math.sqrt(e) / float(w0.norm()), "shape": [n, m]}
    s = torch.linalg.svdvals(dw)
    p = s / s.sum()
    out["erank"] = float(torch.exp(-(p * torch.log(p.clamp_min(1e-300))).sum())) / min(n, m)
    c = torch.cumsum(s**2, 0) / (s**2).sum()
    out["r90"] = (int((c < 0.9).sum()) + 1) / min(n, m)
    U, S, Vh = base_svd
    k = max(1, round(KFRAC * min(n, m)))
    Uk, Vk = U[:, :k], Vh[:k].T
    left = float(((Uk.T @ dw) ** 2).sum()) / e
    right = float(((dw @ Vk) ** 2).sum()) / e
    both = float(((Uk.T @ dw @ Vk) ** 2).sum()) / e
    out.update(
        k=k,
        inside=both,
        inside_rand=k * k / (n * m),
        align=both / (k * k / (n * m)),
        outside=1 - both,
        left=left,
        left_rand=k / n,
        right=right,
        right_rand=k / m,
        base_top_energy=float((S[:k] ** 2).sum() / (S**2).sum()),
        sparsity=float((dw.abs() <= 1e-6 * float(w0.abs().max())).double().mean()),
    )
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "stage0.json"))
    ap.add_argument("--md_only", action="store_true", help="rewrite stage0.md from the json")
    a = ap.parse_args(argv)
    if a.md_only:
        write_md(json.loads(Path(a.out).read_text()))
        return 0
    torch.set_num_threads(8)
    reg = registry()
    res: dict[str, dict] = {}
    for seed in (0, 1, 2):
        base = reg[("base", seed)]
        W0 = matrices(state_dict(base.path))
        svd = {k: torch.linalg.svd(v.double(), full_matrices=False) for k, v in W0.items()}
        for (label, s), c in sorted(reg.items(), key=lambda kv: kv[1].R):
            if s != seed or label == "base":
                continue
            W = matrices(state_dict(c.path))
            per = {k: metrics(W0[k], W[k] - W0[k], svd[k]) for k in W0}
            res[f"{label}|s{seed}"] = {"label": label, "seed": seed, "R": c.R, "per": per}
            print(label, seed, f"R={c.R:.2e}", flush=True)
    for v in res.values():
        blk = [m for k, m in v["per"].items() if k.startswith("b")]
        v["median"] = {
            key: float(np.median([m[key] for m in blk]))
            for key in ("rel", "erank", "r90", "inside", "align", "outside", "left", "right")
        }
        v["median"]["sparsity"] = float(np.median([m["sparsity"] for m in blk]))
        v["frac_erank_ge_0.5"] = float(np.mean([m["erank"] >= 0.5 for m in blk]))
        v["by_kind"] = {
            kind: {
                key: float(np.median([m[key] for k, m in v["per"].items() if k.endswith(kind)]))
                for key in ("rel", "erank", "align", "left", "right")
            }
            for kind in (".q", ".k", ".v", ".proj", ".fc1", ".fc2")
        }
    with open(a.out, "w") as f:
        json.dump(res, f, indent=1)
    write_md(res)
    return 0


def spearman(x: list[float], y: list[float]) -> float:
    rx = np.argsort(np.argsort(x)).astype(float)
    ry = np.argsort(np.argsort(y)).astype(float)
    return float(np.corrcoef(rx, ry)[0, 1])


def write_md(res: dict[str, dict]) -> None:
    lines = [
        "# Stage 0 numbers (generated by `stage0_weights.py`)",
        "",
        "Medians over the 36 block matrices (q, k, v, proj, fc1, fc2 in 6 blocks). `inside` is "
        "the share of ‖ΔW‖² in the base's top-10% left and right singular subspaces; its random "
        "expectation is k²/(n·m): 1.0% for the 384 × 384 matrices and 0.3% for fc1 / fc2 "
        "(k = 38). `align` = inside / expectation.",
        "",
        "| checkpoint | seed | R | rel | erank | r90 | inside | align | left | right "
        "| sparsity | erank≥0.5 |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for v in sorted(res.values(), key=lambda v: (v["seed"], v["R"])):
        md = v["median"]
        lines.append(
            f"| {v['label']} | {v['seed']} | {v['R']:.2e} | {100 * md['rel']:.3f}% "
            f"| {md['erank']:.3f} | {md['r90']:.3f} | {100 * md['inside']:.2f}% "
            f"| {md['align']:.2f} | {100 * md['left']:.1f}% | {100 * md['right']:.1f}% "
            f"| {100 * md['sparsity']:.2f}% | {100 * v['frac_erank_ge_0.5']:.0f}% |"
        )
    s0 = [v for v in res.values() if v["seed"] == 0 and math.isfinite(v["R"])]
    rho = spearman([v["R"] for v in s0], [v["median"]["rel"] for v in s0])
    lines += [
        "",
        f"Spearman ρ(R, median rel), seed-0 chain, {len(s0)} checkpoints: {rho:.3f}.",
        "",
        "## By matrix kind at the L3 end (seed 0)",
        "",
        "| kind | rel | erank | align | left | right |",
        "|---|---|---|---|---|---|",
    ]
    for kind, d in res["L3|s0"]["by_kind"].items():
        lines.append(
            f"| {kind[1:]} | {100 * d['rel']:.2f}% | {d['erank']:.3f} | {d['align']:.2f} "
            f"| {100 * d['left']:.1f}% | {100 * d['right']:.1f}% |"
        )
    (HERE / "stage0.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    raise SystemExit(main())
