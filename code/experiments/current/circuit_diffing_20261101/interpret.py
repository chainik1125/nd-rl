"""Top activations of a crosscoder's strict RL-only latents (and, for contrast, random shared
ones) on the held-out sequences.

    python -m code.experiments.current.circuit_diffing_20261101.interpret --gpu 0 --cc DIR

Per latent: firing rate per source, the share of firings in the state, think and action parts of
a step, the tokens it fires on most, and its 8 strongest contexts (40 tokens before the firing
token, which is marked [[ ]], and 4 after). Writes `interpret_<cc>.md` and `.json` here.
"""

from __future__ import annotations

import argparse
import collections
import json
import os
from pathlib import Path
from typing import Any

import numpy as np

from .common import HERE, assert_gpu_free, pt_now, registry
from .crosscoder import Acts, load_meta, load_seqs

SRC_NAMES = {"b_roll": "RL rollouts", "a_roll": "base rollouts", "pretrain": "pretraining"}


def region(seq: np.ndarray, gen_start: int, pos: int, end_think: int) -> str:
    if pos < gen_start:
        return "state"
    close = np.flatnonzero(seq[gen_start:] == end_think)
    if len(close) and pos > gen_start + int(close[0]):
        return "action"
    return "think"


def run(a: argparse.Namespace) -> None:
    import torch

    from .common import load_model
    from .patching import load_cc
    from .stage1_analyze import arrays, classify

    dev = a.device
    cc_dir = Path(a.cc)
    cc, meta = load_cc(cc_dir, dev)
    reg = registry()
    la, sa = meta["a"].split(":")
    lb, sb = meta["b"].split(":")
    ma, tok, _ = load_model(reg[(la, int(sa))].path, dev)
    mb, _, _ = load_model(reg[(lb, int(sb))].path, dev)
    acts = Acts(ma, mb, int(meta["layer"]), dev)
    acts.scale = torch.tensor(meta["scale"], device=dev)
    L = arrays(torch.load(cc_dir / "latents.pt", weights_only=False))
    c = classify(L)
    ev = json.loads((cc_dir / "eval.json").read_text())
    ev_var = [ev["per_source"][s]["var"][1] for s in SRC_NAMES]
    rl = np.flatnonzero(c["rl"])
    live = c["live"]
    absent = np.flatnonzero(
        live & ~c["rl"] & (np.abs(c["nu_eps_rl"]) < 0.3) & (np.abs(c["nu_r_rl"]) < 0.3)
    )
    eb = sum(L[f"energy_b_{s}"] for s in SRC_NAMES)
    rot_pool = np.flatnonzero(live & (L["cos"] < 0.5))
    rot = rot_pool[np.argsort(-eb[rot_pool])][: a.n_rot]
    rot = np.setdiff1d(rot, absent)
    rng = np.random.default_rng(0)
    shared = np.flatnonzero(c["shared"] & (L["cos"] > 0.9))
    ctrl = rng.choice(shared, size=min(len(shared), a.n_ctrl), replace=False)
    lat = np.concatenate([rl, absent, rot, ctrl])
    kind = (
        {int(j): "RL-only (strict)" for j in rl}
        | {int(j): "RL direction absent in base (exploratory |ν| < 0.3)" for j in absent}
        | {int(j): "rotated (decoder cos < 0.5), high energy" for j in rot}
        | {int(j): "shared control (cos > 0.9)" for j in ctrl}
    )
    sel = torch.as_tensor(lat, device=dev)
    end_think = tok.stoi["</think>"]
    top: dict[int, list[tuple[float, str, int, int]]] = {int(j): [] for j in lat}
    fires: dict[int, collections.Counter] = {int(j): collections.Counter() for j in lat}
    toks: dict[int, collections.Counter] = {int(j): collections.Counter() for j in lat}
    store: dict[str, tuple[list[np.ndarray], np.ndarray]] = {}
    held = meta["held_out"]
    for src, p in meta["sources"].items():
        seqs = load_seqs(Path(p))
        md = load_meta(Path(p))
        ho = held[src][: a.max_seqs]
        hs = [seqs[i] for i in ho]
        gs = md["gen_start"][ho]
        store[src] = (hs, gs)
        x, lens = acts.run(hs)
        f, _ = cc.encode(x)
        fsel = f[:, sel].float().cpu().numpy()
        off = np.concatenate([[0], np.cumsum(lens)])
        seq_of = np.repeat(np.arange(len(hs)), lens)
        pos_of = np.arange(off[-1]) - off[seq_of]
        for col, j in enumerate(lat):
            nz = np.flatnonzero(fsel[:, col] > 0)
            j = int(j)
            fires[j][src] += len(nz)
            fires[j][src + "_tokens"] += int(off[-1])
            for t in nz:
                s, q = int(seq_of[t]), int(pos_of[t])
                fires[j][region(hs[s], int(gs[s]), q, end_think)] += 1
                toks[j][tok.itos[int(hs[s][q])]] += 1
            best = nz[np.argsort(-fsel[nz, col])[: a.top]]
            top[j] += [(float(fsel[t, col]), src, int(seq_of[t]), int(pos_of[t])) for t in best]
        del x, f
    out: dict[str, Any] = {"cc": str(cc_dir), "latents": []}
    lines = [
        f"# Top activations: `{cc_dir.name}` (generated by `interpret.py`)",
        "",
        f"{len(rl)} strict RL-only latents, {len(absent)} latents whose RL direction is absent "
        f"from the base by Latent Scaling alone (exploratory), the {len(rot)} highest-energy "
        f"rotated latents, and {len(ctrl)} random shared latents as a contrast. "
        "Contexts are held-out sequences: one environment step each (state, `<eB> <think>`, "
        "think block, `</think>`, action). The firing token is in [[ ]].",
        "",
    ]
    for j in lat:
        j = int(j)
        fc = fires[j]
        reg_tot = sum(fc[r] for r in ("state", "think", "action")) or 1
        rate = {s: fc[s] / max(1, fc[s + "_tokens"]) for s in SRC_NAMES}
        doc = dict(
            latent=j,
            kind=kind[j],
            dnorm=float(c["dnorm"][j]),
            cos=float(L["cos"][j]),
            energy_share_b=float(eb[j] / sum(ev_var)),
            nu_eps=float(c["nu_eps_rl"][j]),
            nu_r=float(c["nu_r_rl"][j]),
            fire_rate=rate,
            region_share={r: fc[r] / reg_tot for r in ("state", "think", "action")},
            top_tokens=toks[j].most_common(8),
            contexts=[],
        )
        lines += [
            f"## latent {j} ({kind[j]})",
            "",
            f"Δnorm {doc['dnorm']:.3f}, decoder cos {doc['cos']:.2f}, ν^ε {doc['nu_eps']:.2f}, "
            f"ν^r {doc['nu_r']:.2f}, RL variance share {100 * doc['energy_share_b']:.3f}%. Firing "
            "rate: "
            + ", ".join(f"{SRC_NAMES[s]} {100 * rate[s]:.3f}%" for s in SRC_NAMES)
            + ". Region: "
            + ", ".join(f"{r} {100 * v:.0f}%" for r, v in doc["region_share"].items())
            + ". Top tokens: "
            + ", ".join(f"`{t}` {n}" for t, n in doc["top_tokens"])
            + ".",
            "",
        ]
        for v, src, s, q in sorted(top[j], reverse=True)[: a.top]:
            hs, gs = store[src]
            seq = hs[s]
            lo = max(0, q - 40)
            words = [tok.itos[int(t)] for t in seq[lo : q + 5]]
            words[q - lo] = f"[[{words[q - lo]}]]"
            ctx = " ".join(words)
            reg_ = region(seq, int(gs[s]), q, end_think)
            doc["contexts"].append(dict(act=v, source=src, region=reg_, text=ctx))
            lines.append(f"- {v:.2f}, {SRC_NAMES[src]}, {reg_}: `{ctx}`")
        lines.append("")
        out["latents"].append(doc)
    name = cc_dir.name
    (HERE / f"interpret_{name}.json").write_text(json.dumps(out, indent=1))
    (HERE / f"interpret_{name}.md").write_text("\n".join(lines) + "\n")
    print(f"{pt_now()} wrote interpret_{name}.md ({len(rl)} RL-only)", flush=True)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cc", required=True)
    ap.add_argument("--gpu", type=int, default=None)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--top", type=int, default=8)
    ap.add_argument("--n_ctrl", type=int, default=4)
    ap.add_argument("--n_rot", type=int, default=5)
    ap.add_argument("--max_seqs", type=int, default=3000)
    a = ap.parse_args(argv)
    if a.device == "cuda":
        assert a.gpu is not None
        assert_gpu_free(a.gpu)
        os.environ["CUDA_VISIBLE_DEVICES"] = str(a.gpu)
    run(a)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
