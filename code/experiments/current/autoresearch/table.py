#!/usr/bin/env python3
"""Regenerate RESULTS.md from results/*/params.json + results.json.   python3 table.py"""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
rows = []
for d in sorted(glob.glob(f'{HERE}/results/[0-9]*/')):
    p = json.load(open(f'{d}/params.json'))
    r = json.load(open(f'{d}/results.json')) if os.path.exists(f'{d}/results.json') else {}
    b = p['protocol']['budget']
    curve = r.get('pretrain', {}).get('curve') or []
    rows.append([p['id'], p['title'], p['model'], ', '.join(p['tags']), p['p_keep'],
                 f"{b['total_secs']}/{b['pretrain_secs']}/{p['protocol']['rl']['rounds']}",
                 p['patch_lines'] if 'patch_lines' in p else '',
                 r.get('metric'), r.get('metric_rl'), r.get('status', 'running'),
                 r.get('pretrain', {}).get('heldout_greedy'), curve[-1].get('val_loss') if curve else '',
                 ' '.join(str(x['targets_solved']) for x in r.get('rl_rounds', [])),
                 r.get('total_secs'), (r.get('surprise') or '').replace('|', '\\|')])
hdr = ['id', 'title', 'agent', 'tags', 'p_keep', 'budget s/pre/rounds', 'patch', 'metric', 'RL solved', 'status',
       'greedy', 'val loss', 'solved by round', 'total s', 'surprise']
out = ['# Autoresearch results (auto-generated by table.py from results/*/)', '',
       '| ' + ' | '.join(hdr) + ' |', '| ' + ' | '.join('---' for _ in hdr) + ' |']
out += ['| ' + ' | '.join('' if x is None else str(x) for x in row) + ' |' for row in rows]
open(f'{HERE}/RESULTS.md', 'w').write('\n'.join(out) + '\n')
print(f'{len(rows)} rows -> RESULTS.md')
