"""The completeness fallback (`searchcomplete.py`, `searchtrace --complete`): default output is
byte-identical to the generator as committed (79749ce), default successes are unchanged under
`complete=True`, and proofs the default search cannot finish are repaired, reference-free, with
strictly valid traces."""

from __future__ import annotations

import hashlib
import inspect
import json
from pathlib import Path
from typing import Any

import pytest

from code.thinking import searchcomplete as sc
from code.thinking import searchtrace as st

from ._pipeline_helpers import k12_head, needs_k12

T = st.td()
needs_fork = pytest.mark.skipif(
    not Path("/scratch/cowifornia/nd-rl/think/nd-takehome/minlen.py").exists(),
    reason="the fork clone (minlen) is not available",
)
# sha256 over the first 120 K12 rows' records (json.dumps + newline; a failure as {"failed": msg}),
# default flags and labels, generated by searchtrace.py at commit 79749ce
GOLDEN = {
    0: "66ddcbc327488f199c7d2f9a2b070da1f179326c88d84cbcf0270e4b38d5b967",
    64: "ef3dc94a6c355683e77e3e467a1faf7c223b3fe2fd3300f4a87a5a8f7afb5cc1",
    256: "2607ecccf1c4d9fc3f096fc3abcf16000788b47a0d8602172279dc6b5343ff94",
    "auto": "784839fa6d975ae6be04dcabbfc606270a041d8a35d7b4258512cd39791fe78f",
}
# K12 theorems the default generator cannot finish (every strategy fails)
HARD = (457, 836, 1483, 2345, 4044)


def _k12_rows(ids: tuple[int, ...]) -> dict[int, dict[str, Any]]:
    out: dict[int, dict[str, Any]] = {}
    with open(st.pt.K12) as f:
        for i, line in enumerate(f):
            if i in ids:
                out[i] = json.loads(line)
            if i >= max(ids):
                break
    return out


@needs_k12
@pytest.mark.parametrize("level", [0, 64, 256, "auto"])
def test_default_output_is_byte_identical_to_the_committed_generator(level: Any) -> None:
    h = hashlib.sha256()
    for i, r in enumerate(k12_head(120)):
        try:
            rec, _, _ = st.trace_for(f"k12_{i}", r["prompt"], level, reference=r["proof"])
        except st.ProofFail as e:
            rec = {"failed": str(e)}
        h.update((json.dumps(rec) + "\n").encode())
    assert h.hexdigest() == GOLDEN[level]


@needs_k12
def test_complete_mode_leaves_default_successes_unchanged() -> None:
    for i, r in enumerate(k12_head(40)):
        a = st.trace_for(f"k12_{i}", r["prompt"], 256, reference=r["proof"])[0]
        b = st.trace_for(f"k12_{i}", r["prompt"], 256, reference=r["proof"], complete=True)[0]
        assert a == b and "complete" not in b["gen"]


def test_the_planner_reads_the_state_only() -> None:
    for fn in (sc.prove_complete, sc.make_plan):
        assert not set(inspect.signature(fn).parameters) & {"proof", "reference", "ref"}


@needs_k12
@needs_fork
def test_complete_mode_repairs_what_the_default_cannot_prove() -> None:
    for i, r in _k12_rows(HARD).items():
        pid = f"k12_{i}"
        with pytest.raises(st.ProofFail):
            st.trace_for(pid, r["prompt"], 256, labels=False)
        rec, infos, pinfo = st.trace_for(pid, r["prompt"], 256, complete=True)
        v = T.validate(rec, lean=False, strict=True)
        assert v["ok"], (pid, v["error"])
        assert rec["gen"]["complete"]["plans"] >= 1 and pinfo["complete"]
        for s, inf in zip(rec["steps"], infos, strict=True):
            if s.get("planner"):  # a planned move the search did not make: no record
                assert inf["planner"] and s["think"] == ""
        # the same theorem without its reference gives the same record
        assert st.trace_for(pid, r["prompt"], 256, complete=True, reference=r["proof"])[0] == rec


@needs_k12
@needs_fork
def test_a_plan_closes_the_frame_it_was_made_for() -> None:
    r = _k12_rows((1483,))[1483]
    env = T.Env(r["prompt"], canon=True, base=0, assign=False)
    for k in range(len(env.prem)):
        env.apply(
            ["have", T.next_names(env)[0], ":", *st.ftoks(env.prem[k]), ":=", f"h{k + 1}", ";"]
        )
    strat = st.make_strategy("dfs", "k12_1483")
    for _ in range(3):  # walk into a box with the honest search
        act = st.Search(env, strat, st.budget_for(0)).run().action
        env.apply(act)
    depth = len(env.frames)
    plan = sc.make_plan(env, 20.0)
    assert plan is not None
    while not plan.done:
        a = plan.next_action(env)
        assert st.viable(env, a), a
        ok, why = env.apply(a)
        assert ok, why
        plan.advance(a, env)
    assert env.done or len(env.frames) < depth or env.frames[-1].kind == "or2"


def test_the_planner_premises_are_a_minimal_support_of_the_goal() -> None:
    P, Q, R = ("atom", "P"), ("atom", "Q"), ("atom", "R")
    hyps = [("imp", P, Q), R, P, ("imp", R, Q)]
    sup = sc.support(hyps, Q)
    assert st.pt.ent(sup, Q)
    assert all(not st.pt.ent([h for h in sup if h != x], Q) for x in sup)  # minimal
    assert sup == [R, ("imp", R, Q)]  # the oldest redundant hypotheses go first
    incons = [P, ("not", P), R]
    assert sc.support(incons, ("bot",)) == [P, ("not", P)]  # a minimal inconsistent core
    assert sc.support(hyps, ("imp", P, P)) == []  # a valid goal needs no premises


@needs_k12
@needs_fork
def test_the_last_resort_plans_the_whole_theorem_and_closes_the_proof(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setattr(sc, "_backoff", lambda env, snaps, *a: (len(snaps), None))
    for i, r in _k12_rows((457, 2345)).items():  # first trigger: depth, stuck
        rec = st.trace_for(f"k12_{i}", r["prompt"], 256, complete=True)[0]
        assert rec["gen"]["complete"]["root_fallbacks"] == 1
        v = T.validate(rec, lean=False, strict=True)
        assert v["ok"], (i, v["error"])


@needs_fork
def test_a_goal_already_in_scope_is_planned_as_exact() -> None:
    env = T.Env("THM ( P & Q ) , R SEQ R PRF", canon=True, base=0, assign=False)
    for k in range(len(env.prem)):
        env.apply(
            ["have", T.next_names(env)[0], ":", *st.ftoks(env.prem[k]), ":=", f"h{k + 1}", ";"]
        )
    plan = sc.make_plan(env, 1.0)  # minlen itself returns no proof when the goal is a premise
    assert plan is not None and plan.length == 1
    act = plan.next_action(env)
    assert act == ["exact", "n2"] and env.apply(act)[0] and env.done
    # the goal in scope but not the last name: `exact` cites the last name only, so restate it
    env = T.Env("THM R , ( P & Q ) SEQ R PRF", canon=True, base=0, assign=False)
    for k in range(len(env.prem)):
        env.apply(
            ["have", T.next_names(env)[0], ":", *st.ftoks(env.prem[k]), ":=", f"h{k + 1}", ";"]
        )
    plan = sc.make_plan(env, 1.0)
    assert plan is not None and plan.length == 2
    while not plan.done:
        act = plan.next_action(env)
        assert st.viable(env, act), act
        env.apply(act)
        plan.advance(act, env)
    assert env.done
